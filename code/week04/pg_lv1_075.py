# 문제 설명
# 어떤 문장의 각 알파벳을 일정한 거리만큼 밀어서 다른 알파벳으로 바꾸는 암호화 방식을 시저 암호라고 합니다. 예를 들어 "AB"는 1만큼 밀면 "BC"가 되고, 3만큼 밀면 "DE"가 됩니다. "z"는 1만큼 밀면 "a"가 됩니다. 문자열 s와 거리 n을 입력받아 s를 n만큼 민 암호문을 만드는 함수, solution을 완성해 보세요.

# 제한 조건
# 공백은 아무리 밀어도 공백입니다.
# s는 알파벳 소문자, 대문자, 공백으로만 이루어져 있습니다.
# s의 길이는 8000이하입니다.
# n은 1 이상, 25이하인 자연수입니다.


def solution(s, n):
    answer = ""
    for c in s:
        if c.isupper():
            answer += chr((ord(c)+n-ord("A"))%26 + ord("A"))
        elif c == " " : 
            answer += " "
        else :
            answer += chr((ord(c)+n-ord("a"))%26 + ord("a"))
    return answer


# 시저 암호 피드백:
# 잘한 점:

# ASCII 코드로 변환 → n 더하기 → 다시 문자로 변환하는 전체 흐름은 정확했어
# 범위 초과 시 순환시켜야 한다는 걸 인지한 것도 좋았어

# 못한 점:

# 순환 계산에서 숫자를 감으로 잡았어. %60, %96은 근거 없이 나온 값이야. ASCII 테이블 구조를 정확히 파악하고 접근했어야 해
# 공백 처리 조건을 설계에 명시 안 했어. 구현할 때 빠뜨릴 수 있는 부분이야

# 새로 배운 패턴: (ord(char) - ord('a') + n) % 26 + ord('a')