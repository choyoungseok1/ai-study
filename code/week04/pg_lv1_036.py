# 문제 설명
# 명함 지갑을 만드는 회사에서 지갑의 크기를 정하려고 합니다. 다양한 모양과 크기의 명함들을 모두 수납할 수 있으면서, 작아서 들고 다니기 편한 지갑을 만들어야 합니다. 이러한 요건을 만족하는 지갑을 만들기 위해 디자인팀은 모든 명함의 가로 길이와 세로 길이를 조사했습니다.

# 아래 표는 4가지 명함의 가로 길이와 세로 길이를 나타냅니다.

# 명함 번호	가로 길이	세로 길이
# 1	60	50
# 2	30	70
# 3	60	30
# 4	80	40
# 가장 긴 가로 길이와 세로 길이가 각각 80, 70이기 때문에 80(가로) x 70(세로) 크기의 지갑을 만들면 모든 명함들을 수납할 수 있습니다. 하지만 2번 명함을 가로로 눕혀 수납한다면 80(가로) x 50(세로) 크기의 지갑으로 모든 명함들을 수납할 수 있습니다. 이때의 지갑 크기는 4000(=80 x 50)입니다.

# 모든 명함의 가로 길이와 세로 길이를 나타내는 2차원 배열 sizes가 매개변수로 주어집니다. 모든 명함을 수납할 수 있는 가장 작은 지갑을 만들 때, 지갑의 크기를 return 하도록 solution 함수를 완성해주세요.

# 제한사항
# sizes의 길이는 1 이상 10,000 이하입니다.
# sizes의 원소는 [w, h] 형식입니다.
# w는 명함의 가로 길이를 나타냅니다.
# h는 명함의 세로 길이를 나타냅니다.
# w와 h는 1 이상 1,000 이하인 자연수입니다.

def solution(sizes):
    answer = 0
    size_s = [sorted(sizes[i]) for i in range(len(sizes))]
    a,b = size_s[0][0], size_s[0][1]
    for j in range(len(sizes)):
        a = max(a,size_s[j][0])
        b = max(b,size_s[j][1])
    return a*b


# 최소직사각형 문제 피드백
# 잘한 점

# 핵심 발상 빠르게 잡음 ("긴쪽 max × 짧은쪽 max") — 풀이 방향 정확
# 각 명함 내부 sort로 (짧은쪽, 긴쪽) 통일하는 발상 좋음
# 컴프리헨션 사용 ([sorted(sizes[i]) for i in range(len(sizes))]) — 깔끔

# 개선할 점

# "덮어쓰기 vs 누적" 패턴 또 발생 (반복되는 약점)

# 학습 플랜에 이미 등록된 약점이 또 나옴
# for문 안에서 a = max(size_s[0][0], size_s[j][0]) — 매 반복마다 덮어쓰기. 이전 비교 결과 사라짐
# 누적 max는 항상 자기 자신과 비교: a = max(a, 새값) 패턴
# 코드 짜기 전 자문: "이 변수가 매 반복마다 누적돼야 하나, 매번 새로 계산되는 건가?"


# 불필요한 인덱싱

# [sorted(sizes[i]) for i in range(len(sizes))] → [sorted(s) for s in sizes]
# 인덱스 i가 필요 없을 때는 직접 원소 순회가 파이썬다움
# 인덱스 쓰는 건 (a) 두 리스트 동시 순회, (b) 인덱스 자체가 의미 있을 때만


# 루프가 j=1부터 시작하는 이유 불분명

# range(1, len(sizes)) → size_s[0]을 기준으로 비교? 그러면 size_s[0] 자체가 누락됨
# 사실 그래서 동작도 안 함. 누적으로 바꾸면 0부터 도는 게 자연스러움


