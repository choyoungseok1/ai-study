"""
프로그래머스 Lv2 - 뒤에 있는 큰 수 찾기
=================================================================

[문제 설명]
정수 배열 numbers의 각 원소에 대해, 자신보다 뒤에 있으면서 자신보다 크고
가장 가까이 있는 수를 "뒷 큰수"라 한다. 모든 원소의 뒷 큰수를 차례로 담은 배열을
return. 뒷 큰수가 없는 원소는 -1.

[제한사항]
- 4 <= numbers의 길이 <= 1,000,000
- 1 <= numbers[i] <= 1,000,000

[복잡도 분석 ★ — 풀이를 결정하는 핵심]
길이가 최대 100만. 각 원소마다 뒤를 쭉 훑으면 O(n^2) = 1조 번 → 무조건 시간초과.
→ O(n) 또는 O(n log n)이어야 한다. "단순 이중 반복 불가" 신호.
→ 단조 스택(monotonic stack)으로 O(n) 해결.

[핵심 발상 — 단조 스택]
스택에 "아직 자기보다 큰 수를 못 만난 원소들"을 쌓아둔다.
새 원소를 볼 때마다:
  - 새 원소가 스택 꼭대기보다 크면 → 꼭대기 입장에선 "얘가 내 뒷 큰수!" → pop하고 기록
  - 크는 한 계속 반복 (여러 개가 한꺼번에 답을 찾을 수 있음)
  - 그다음 새 원소를 push
비유: 일렬로 선 사람들이 각자 "내 뒤에서 나보다 키 큰 첫 사람"을 기다림.
      새 사람이 오면, 그보다 작아 기다리던 사람들이 한꺼번에 "쟤다!" 하고 답을 찾음.

[두 가지 함정]
1. 스택에 값이 아니라 '인덱스'를 넣는다.
   → 답은 원래 위치(answer[i])에 채워야 하므로, pop할 때 "원래 몇 번째였는지"가 필요.
     인덱스를 넣으면 위치(answer[idx])도, 값(numbers[idx])도 둘 다 잡힌다.
     값만 넣으면 위치를 잃어버려 답을 어디 적을지 모름.
2. 끝까지 스택에 남은 원소 = 뒷 큰수를 못 만난 애들 → 답은 -1.
   → answer를 처음부터 [-1]*n으로 초기화하면, 찾은 애만 덮어쓰고 남은 애는
     자동으로 -1인 채로 남는다. 따로 뒤처리 불필요.
"""


# =================================================================
# 풀이 - 단조 스택 (O(n))  ★ 직접 푼 풀이
# =================================================================

def solution(numbers):
    answer = [-1] * len(numbers)   # 전부 -1로 시작 (못 찾은 애는 자동 -1)
    stack = []                      # 인덱스를 쌓을 스택

    for i in range(len(numbers)):           # 왼쪽부터 한 번 순회
        # 스택 꼭대기보다 numbers[i]가 크면 → 그 꼭대기는 뒷 큰수를 찾음
        # 크는 한 계속 pop (여러 개가 한꺼번에 해결될 수 있음)
        while stack and numbers[i] > numbers[stack[-1]]:
            idx = stack.pop()
            answer[idx] = numbers[i]
        stack.append(i)             # 현재 인덱스 push

    return answer


# =================================================================
# 왜 O(n)인가 (중첩 루프인데도)
# =================================================================
# for 안에 while이 중첩돼 언뜻 O(n^2) 같지만:
#   각 인덱스는 스택에 딱 1번 push되고, 최대 1번 pop된다.
#   → 전체 pop 횟수 <= 전체 push 횟수 = n
#   → for + while 합쳐서 연산이 2n 수준 = O(n)
# "중첩 루프 = O(n^2)"가 항상 참은 아니라는 좋은 반례.
# 이 분할상환(amortized) O(n)이 100만 길이를 통과시키는 비결.


# =================================================================
# 같은 패턴이 나오는 다른 문제들 (단조 스택)
# =================================================================
# "다음으로 큰/작은 원소 찾기" 류는 전부 이 패턴:
#   - 주식 가격 (며칠 뒤 가격이 오르나)
#   - 히스토그램에서 최대 직사각형
#   - 일일 온도 (다음 더운 날까지 며칠)
# → "다음으로 큰/작은 거 찾기"가 보이면 단조 스택을 떠올린다.


