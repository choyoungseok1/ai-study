"""
프로그래머스 Lv2 - 호텔 대실
=================================================================

[문제 설명]
호텔을 운영 중인 코니는 최소한의 객실만을 사용하여 예약 손님들을 받으려고 한다.
한 번 사용한 객실은 퇴실 시간을 기준으로 10분간 청소를 하고 다음 손님이 사용할 수 있다.
예약 시각이 담긴 2차원 배열 book_time이 주어질 때, 필요한 최소 객실 수를 return.

[제한사항]
- 1 <= book_time의 길이 <= 1,000
- book_time[i] = ["HH:MM", "HH:MM"]  → [대실 시작, 대실 종료]
- 24시간 표기, "00:00" ~ "23:59"
- 자정을 넘어가는 예약 없음, 시작 < 종료 보장

[핵심 발상]
1. "HH:MM" 문자열을 분 단위 정수로 변환
2. 각 예약을 [시작, 종료+10] 구간으로 만든다 (10 = 청소시간)
3. 가장 많이 겹치는 구간 수 = 필요한 최소 객실 수

[경계 판단 ★]
청소가 끝나는 그 순간(예: 11:00)에 다음 손님이 바로 들어올 수 있다.
→ 한 방의 (종료+청소) 시각과 다음 손님의 시작 시각이 "같으면" 두 손님은 같은 방을 쓸 수 있다.
→ 겹친다고 보지 않는다. 부등호로 <= 를 쓰는 이유.
"""


# =================================================================
# 풀이 B — 타임라인 훑기 (sweep line)  ★ 제출한 풀이
# =================================================================
# 발상: 시작 시각엔 방이 하나 켜지고(+1), 종료 시각엔 꺼진다(-1).
#       시간 순으로 쭉 따라가며 "동시에 켜진 방 수"의 최댓값을 찾는다.
#       (병원 대기실: 누가 들어오면 +1, 나가면 -1. 가장 붐빈 순간의 인원 = 필요한 의자 수)

def solution_sweep(book_time):
    events = []
    for start, end in book_time:
        start_min = int(start[:2]) * 60 + int(start[3:])
        end_min = int(end[:2]) * 60 + int(end[3:]) + 10  # +10 청소시간
        events.append((start_min, 1))   # 시작 → 방 하나 켜짐
        events.append((end_min, -1))    # 종료(+청소) → 방 하나 꺼짐

    # (시각, 증감값) 튜플 정렬.
    # 같은 시각이면 -1 < +1 이므로 종료(-1)가 시작(+1)보다 먼저 처리됨.
    # → 11:00에 한 명 청소 끝나고(-1) 한 명 시작(+1)하면, 먼저 빠진 뒤 들어와서
    #   같은 방 재사용으로 카운트됨. (경계 규칙이 정렬 한 방에 자동 반영됨)
    events.sort()

    cur = answer = 0
    for time, delta in events:
        cur += delta                    # 누적(+=). 덮어쓰기(=) 아님에 주의
        answer = max(answer, cur)
    return answer


# =================================================================
# 풀이 A — 구간 직접 비교 / 그리디 방 배정 (시뮬레이션)
# =================================================================
# 발상: 손님을 도착(시작) 순으로 받으면서,
#       빈 방이 있으면 재사용하고 없으면 새 방을 추가한다. 실제 호텔 운영을 그대로 흉내.
#       마지막에 만들어진 방의 개수 = 답.

def solution_greedy(book_time):
    times = []
    for start, end in book_time:
        s = int(start[:2]) * 60 + int(start[3:])
        e = int(end[:2]) * 60 + int(end[3:]) + 10
        times.append((s, e))
    times.sort()  # 시작 시각 순 — 손님을 도착 순서대로 받기 위해

    rooms = []  # 각 방의 "마지막 (퇴실+청소) 완료 시각"
    for s, e in times:
        assigned = False
        for i in range(len(rooms)):
            if rooms[i] <= s:      # 이 방은 청소까지 끝나서 비어있음 → 재사용
                rooms[i] = e       # 내 (퇴실+청소) 시각으로 갱신
                assigned = True
                break
        if not assigned:           # 들어갈 방이 하나도 없으면
            rooms.append(e)        # 새 방 추가
    return len(rooms)

# A의 경계: rooms[i] <= s
#   방의 (퇴실+청소) 시각이 내 시작 시각과 같아도(=) 들어갈 수 있어야 하므로 < 가 아니라 <=.
#   < 로 쓰면 같은 방을 쓸 수 있는데도 새 방을 잡아 답이 커진다.


# =================================================================
# 두 풀이 비교
# =================================================================
# - sweep(B):   이벤트 2n개 정렬 → 한 번 훑기. 빠르고 짧다. (전체 통계로 본다)
# - greedy(A):  예약마다 방들을 다 뒤짐. 최악엔 방이 예약 수만큼 → 더 느릴 수 있지만
#               "실제로 어떻게 배정되는지"가 눈에 보여 직관적. (하나씩 시뮬레이션한다)
# → 같은 문제를 보는 두 시각. 스케줄링/자원 배정 문제 전반에 계속 등장한다.


