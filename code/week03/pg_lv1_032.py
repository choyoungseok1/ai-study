# N ≤ 3,000,000 보고도 O(N²) 또는 그 이상 짜는 건 이전 약수 문제(기사단원의 무기)랑 같은 패턴의 실수
# 코드 짜기 전에 "입력 크기 보고 허용 시간복잡도 추정" 하는 습관 들이기:

# N ≤ 100 → O(N³) OK
# N ≤ 10,000 → O(N²) OK
# N ≤ 1,000,000 → O(N) 또는 O(N log N)
# N ≤ 100,000,000 → O(N) 또는 O(log N)




