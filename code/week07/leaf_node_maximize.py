"""
========================================================================
[프로그래머스 Lv2] 리프 노드 최대화
풀이: 조영석 | Day 51 (2026-05-29)
========================================================================

[문제 설명]
루트 노드, 리프 노드, 분배 노드로 구성되는 트리가 있다.
- 루트 노드: 자식 1개만 가짐
- 분배 노드: 루트/리프를 제외한 노드. 자식 2개 또는 3개를 가짐
- 리프 노드: 자식 0개

규칙:
  1. 분배 노드는 자식을 2개 또는 3개 가진다.
  2. 분배 노드는 최대 dist_limit개 존재할 수 있다. (예산)
  3. 같은 깊이의 분배 노드는 자식 수가 모두 같아야 한다.
  4. 리프 노드의 '분배도' = 그 리프의 부모에서 루트까지 경로상 모든 노드의
     자식 개수의 곱.
     (예: 경로가 1->3->3이면 분배도 = 1 x 3 x 3 = 9)
  5. 모든 리프 노드의 분배도는 split_limit 이하여야 한다.

목표: 위 조건 하에 만들 수 있는 리프 노드 수의 최댓값을 return.

제한사항:
  0 <= dist_limit  <= 10^9
  1 <= split_limit <= 10^9
========================================================================


------------------------------------------------------------------------
[핵심 아이디어 — 문제를 풀며 도달한 모델]
------------------------------------------------------------------------
처음엔 "모든 리프가 같은 깊이"라고 가정해서, 리프 수 = 각 층 자식수의 곱
(2^i x 3^j) 이라고 생각했다. -> 이건 split=100, dist=3에서 정답 7이 안 나옴.
(7은 2^i x 3^j 꼴로 표현이 안 되는 값)

진짜 구조의 핵심:
  * 리프는 여러 깊이에 흩어질 수 있다. (모든 리프가 같은 깊이일 필요 없음)
    한 분배 노드의 자식 중 일부는 리프, 일부는 다음 분배 노드가 될 수 있다.
  * 분배 1회(자식 k개)는:
        - 예산(dist_limit)을 1 소모
        - 리프 수를 (k-1)만큼 증가  <- ★ 핵심 공식
    (왜 k-1? 자식 k개가 생기지만, 분배한 노드 자신은 더 이상 리프가 아니므로
     순증가 = k - 1)

전략 두 가지가 사실은 하나로 통합된다:
  * 완전 분배 (균일 트리): 한 층의 노드를 전부 분배. 곱이 곧 리프 수.
    -> 예산이 넉넉할 때(=split이 병목) 유리
  * 부분 분배 (체인/리프 떼내기): 한 층의 일부 노드만 분배하고
    나머지는 리프로 남김. -> 예산이 빠듯할 때(=dist가 병목) 유리

  => "완전 분배로 내려가다가, 예산이 모자라는 층에서 부분 분배로 마무리"
     하는 하나의 절차로 합쳐진다.

배치 최적화 (해설 명제):
  * 명제 1: 부분 분배는 한 깊이에서만 일어나도록 정렬할 수 있다.
  * 명제 2: 같은 수의 2분배층과 3분배층을 쓴다면,
            [2분배층을 위 / 3분배층을 아래] 가 예산을 더 적게 쓴다.
            (작은 수가 위에 있을수록 프런티어가 천천히 커져서 예산 절약)
            -> 예: 2->3 순서는 W + 2W = 3W 예산, 3->2 순서는 W + 3W = 4W 예산.
               둘 다 결과 프런티어는 6W로 같지만 2->3이 더 쌈.
  * 그래서 최적 트리는 "위에 연속된 2분배층 i개, 아래에 연속된 3분배층 j개"
    형태. 부분 분배는 많아야 한 층에서만 발생.

검증용 손계산 정답 (작은 케이스):
  dist=0            -> 1   (분배 노드 0개 = 루트+리프1개)
  dist=1, split=100 -> 3   (x3 한 번, 자식 3개 다 리프)
  dist=2, split=100 -> 5
  dist=3, split=100 -> 7   (x3 체인: 2d+1 = 2*3+1 = 7)
  dist=3, split=6   -> 6   (3x2 균일트리 = 곱 6)
------------------------------------------------------------------------
"""


def solution(dist_limit, split_limit):
    answer = 1  # 최소: 루트 + 리프 1개 (분배 노드 0개인 경우)

    # 경로곱(분배도)은 항상 2^i x 3^j 꼴.
    # split_limit(<=10^9) 안에서 2^i, 3^j 의 가능한 지수 범위:
    #   2^30 ~ 10.7억 > 10^9 이므로 i는 30까지면 충분
    #   3^19 ~ 11.6억 > 10^9 이므로 j는 20까지면 충분
    for i in range(32):
        # 2분배만으로 이미 split_limit를 넘으면 더 큰 i는 볼 필요 없음
        if (2 ** i) > split_limit:
            break

        for j in range(21):
            # [규칙 5] 가장 깊은 리프의 분배도 = 2^i x 3^j 가 split_limit 이하여야 함
            if (2 ** i) * (3 ** j) > split_limit:
                break

            # ── 명제 2: [2분배 i층] -> [3분배 j층] 순서로 트리를 구성 ──
            budget = dist_limit  # 남은 분배 노드 예산
            frontier = 1         # 현재 층의 노드 수 (루트의 자식 1개에서 시작)

            went_through_2 = True  # 2분배 구간을 예산 끊김 없이 통과했는지

            # 1) 상단: 2분배를 i개 층 진행
            for _ in range(i):
                if budget >= frontier:
                    # 완전 분배: 이 층의 모든 노드(frontier개)를 분배
                    budget -= frontier
                    frontier *= 2
                else:
                    # 부분 분배: 남은 예산(budget)개 노드만 2분배하고 종료
                    #   리프 순증가 = budget * (2 - 1)
                    #   (분배 안 한 나머지 노드는 그대로 리프로 남아 frontier에 이미 포함)
                    frontier += budget * (2 - 1)
                    budget = 0
                    went_through_2 = False
                    break

            # 2) 하단: 3분배를 j개 층 진행 (2분배 구간을 다 통과한 경우에만)
            if went_through_2:
                for _ in range(j):
                    if budget >= frontier:
                        # 완전 분배
                        budget -= frontier
                        frontier *= 3
                    else:
                        # 부분 분배: 남은 예산만큼 3분배하고 종료
                        #   리프 순증가 = budget * (3 - 1)
                        frontier += budget * (3 - 1)
                        budget = 0
                        break

            # 이 (i, j) 조합에서 얻은 최종 리프 수로 최댓값 갱신
            answer = max(answer, frontier)

    return answer


# ── 직접 검증용 (제출 시에는 지워도 됨) ──
if __name__ == "__main__":
    tests = [
        ((0, 5), 1),
        ((1, 100), 3),
        ((2, 100), 5),
        ((3, 100), 7),
        ((3, 6), 6),
    ]
    for (d, s), expected in tests:
        got = solution(d, s)
        mark = "OK" if got == expected else "X"
        print(f"[{mark}] dist={d}, split={s} -> {got} (정답 {expected})")


