# 처음 물류창고에 놓인 컨테이너의 정보를 담은 1차원 문자열 배열 storage와 출고할 컨테이너의 종류와 출고방법을 요청 순서대로 담은 1차원 문자열 배열 requests가 매개변수로 주어집니다. 이때 모든 요청을 순서대로 완료한 후 남은 컨테이너의 수를 return 하도록 solution 함수를 완성해 주세요.

# 제한사항
# 2 ≤ storage의 길이 = n ≤ 50
# 2 ≤ storage[i]의 길이 = m ≤ 50
# storage[i][j]는 위에서 부터 i + 1번째 행 j + 1번째 열에 놓인 컨테이너의 종류를 의미합니다.
# storage[i][j]는 알파벳 대문자입니다.
# 1 ≤ requests의 길이 ≤ 100
# 1 ≤ requests[i]의 길이 ≤ 2
# requests[i]는 한 종류의 알파벳 대문자로 구성된 문자열입니다.
# requests[i]의 길이가 1이면 지게차를 이용한 출고 요청을, 2이면 크레인을 이용한 출고 요청을 의미합니다.
from collections import deque

def solution(storage, requests):
    n = len(storage)
    m = len(storage[0])
    
    # 1. 외곽을 '.'으로 감싼 격자(grid) 생성 (n+2 x m+2 크기)
    grid = [['.'] * (m + 2) for _ in range(n + 2)]
    for i in range(n):
        for j in range(m):
            grid[i + 1][j + 1] = storage[i][j]
            
    dr = [-1, 1, 0, 0]
    dc = [0, 0, -1, 1]
    
    for req in requests:
        target = req[0]
        
        if len(req) == 2:
            # [크레인] 격자 전체에서 해당 알파벳을 전부 제거
            for r in range(1, n + 1):
                for c in range(1, m + 1):
                    if grid[r][c] == target:
                        grid[r][c] = '.'
        else:
            # [지게차] BFS를 통해 외부에서 접근 가능한 컨테이너 찾기
            visited = [[False] * (m + 2) for _ in range(n + 2)]
            queue = deque([(0, 0)])
            visited[0][0] = True
            
            to_remove = set() # 이번 턴에 지워질 컨테이너 좌표 모음
            
            while queue:
                r, c = queue.popleft()
                
                for d in range(4):
                    nr, nc = r + dr[d], c + dc[d]
                    
                    if 0 <= nr < n + 2 and 0 <= nc < m + 2 and not visited[nr][nc]:
                        if grid[nr][nc] == '.':
                            # 빈 공간이면 계속 바깥 공기가 통하므로 이동 가능
                            visited[nr][nc] = True
                            queue.append((nr, nc))
                        elif grid[nr][nc] == target:
                            # 바깥 공기와 맞닿은 목표 컨테이너 발견!
                            to_remove.add((nr, nc))
            
            # 찾은 컨테이너들을 일괄 제거
            for r, c in to_remove:
                grid[r][c] = '.'
                
    # 2. 남은 컨테이너 수 계산
    answer = 0
    for r in range(1, n + 1):
        for c in range(1, m + 1):
            if grid[r][c] != '.':
                answer += 1
                
    return answer

# 잘한 점1. 큰 그림을 매번 먼저 잡았다. 도둑 문제, 서버 문제, 이 문제 전부 — 코드 짜기 전에 "이렇게 접근하면 될 것 같다"를 먼저 말했고, 그게 거의 정답 방향이었어. 세부에서 막혀도 골격이 맞으니 고쳐나갈 수 있었지. 이게 제일 중요한 능력이야.2. BFS 구현의 핵심 디테일을 정확히 잡았다. 외부 공기 BFS에서 target 컨테이너를 만나면 to_remove에 담되 큐엔 안 넣는 처리. 컨테이너를 벽으로 유지해서 공기가 뚫고 못 가게 한 거 — 이게 틀리기 쉬운 지점인데 한 번에 맞췄어. set으로 중복 처리한 것도 깔끔했고.3. 디버그를 제대로 했다. 답이 10 나왔을 때, 막연히 코드를 뜯어고친 게 아니라 print(remove)로 어떤 좌표가 잘못 담겼는지 찍어서 (2,3)을 특정했어. "현상 → 원인 위치 좁히기 → 확인"이라는 디버깅 정석을 밟았어. 이거 어제 리프노드 때 print로 좁힌 거랑 같은 방식이라, 이제 네 디버깅 습관으로 자리잡은 것 같아.막혔던 지점 (복기용)1. 들여쓰기 — 같은 실수가 세 번 반복됐다.

