"""
==============================================================================
 프로그래머스 Lv2 - 우박수열 정적분
 날짜: 2026-07-29 (Week 15)
 분류: 시뮬레이션 + 누적 구간합 (사다리꼴 면적)
==============================================================================

[문제 설명]
콜라츠 수열(우박수열)을 좌표평면에 꺾은선 그래프로 그리고, 주어진 구간에 대해
정적분(그래프와 x=a, x=b, y=0 으로 둘러싸인 면적)을 구한다.

  초항 k → x=0 에 y=k, 다음 우박수는 x=1 에 ... 1이 될 때까지

구간 [a, b] 에서 b 는 0 이하의 수로 주어지며, 실제 끝점은 n + b 다.
  ★ n = k 가 초항인 우박수열이 1이 될 때까지의 "횟수"

시작점이 끝점보다 크면 유효하지 않은 구간 → -1

[제한사항]
    2 <= k <= 10,000
    1 <= len(ranges) <= 10,000,  0 <= a < 200,  -200 < b <= 0
    정적분 결과는 2^27 을 넘지 않음 (실수형 포함)

[핵심 1 — n 의 정의를 정확히 잡기 ★]
    k=5 → 5 ⇒ 16 ⇒ 8 ⇒ 4 ⇒ 2 ⇒ 1
      점(좌표) 6개: (0,5) (1,16) (2,8) (3,4) (4,2) (5,1)
      화살표(횟수) 5개  →  n = 5 = len(seq) - 1

    여기서 예제 두 개가 갈린다:
      [2, -3] → 끝점 = 5 - 3 = 2 → 구간 [2, 2] → 폭 0 → 면적 0.0  (유효)
      [3, -3] → 끝점 = 5 - 3 = 2 → 구간 [3, 2] → 3 > 2 → 유효하지 않음 → -1
    끝점은 같고 시작점만 다르다. 뒤집힌 구간인지가 유일한 차이.

[핵심 2 — 사다리꼴 면적을 미리 쌓아두기]
    x=i 에서 x=i+1 까지의 면적 = (y_i + y_{i+1}) / 2   (사다리꼴 공식)
    → area[i] 로 미리 계산해두면 구간 [a, b] 의 정적분은
         area[a] + area[a+1] + ... + area[b-1] = sum(area[a:b])

    ★ 슬라이스가 폭 0 케이스를 자동 처리한다:
      a == b 이면 area[a:a] 는 빈 슬라이스 → sum([]) == 0 → 특별 처리 불필요
      (실수 패턴 12번: 특수처리가 새 버그를 낳는다 → 구조로 예외를 없애는 게 정석)

    ⚠️ 슬라이스 끝이 b(미포함)인 것이 맞다.
       x=a~b 구간에는 사다리꼴이 b-a 개 있으므로 인덱스 a..b-1.

[시간복잡도]
    수열 생성    O(길이)         k <= 10,000 이면 길이는 수백 수준
    area 계산    O(길이)
    질의 처리    O(len(ranges) × 구간길이)   구간 길이 <= 200 으로 제한됨
    → 충분히 통과. (구간이 길고 질의가 많으면 누적합(prefix sum)으로 O(1) 질의 가능)
==============================================================================
"""


# =============================================================================
# 1. 제출 코드 (통과)
# =============================================================================

def solution_submitted(k, ranges):
    answer = []
    temp = []
    i = 0
    while k > 1:
        temp.append(k)
        i += 1                       # ⚠️ 이 i 는 어디에도 쓰이지 않음 (아래 피드백)
        if k % 2 == 0:
            k = k // 2               # ⚠️ 파라미터 k 를 덮어씀
        else:
            k = k * 3 + 1
    temp.append(1)
    area = [(temp[i] + temp[i + 1]) / 2 for i in range(len(temp) - 1)]
    n = len(temp) - 1
    for a, b in ranges:
        end = n + b
        if a > end:
            answer.append(-1)
        else:
            answer.append(sum(area[a:end]))
    return answer


# =============================================================================
# 2. 개선 코드
# =============================================================================

def solution(k, ranges):
    # 수열 생성 — 초항 k 를 보존하고 cur 로 굴린다
    seq = [k]
    cur = k
    while cur > 1:
        cur = cur // 2 if cur % 2 == 0 else cur * 3 + 1
        seq.append(cur)

    # 구간별 사다리꼴 면적
    area = [(seq[i] + seq[i + 1]) / 2 for i in range(len(seq) - 1)]
    n = len(area)          # = len(seq) - 1. "사다리꼴 개수 = 우박수열 횟수"

    answer = []
    for a, b in ranges:
        end = n + b        # b <= 0 이므로 더하기
        answer.append(-1 if a > end else sum(area[a:end]))
    return answer


# 개선 포인트
#   - 쓰이지 않는 카운터 i 제거 (n 은 len(area) 로 구함)
#   - 파라미터 k 를 보존하고 cur 를 순회 변수로 분리
#   - n = len(area) 로 잡아 "사다리꼴 개수 = 횟수"라는 의미를 코드에 드러냄
#   - 삼항 연산자로 분기 압축


