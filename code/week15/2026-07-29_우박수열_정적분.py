"""
------------------------------------------------------------------------------
막혔던 지점 — [2,-3] 은 0.0 인데 [3,-3] 은 왜 -1인가
------------------------------------------------------------------------------
n 의 정의를 "1이 될 때까지의 횟수"로 정확히 잡으면 풀린다.
k=5 → n=5 이므로 두 구간의 끝점은 둘 다 5-3=2.
  [2, -3] → [2, 2] : a == end, 폭 0 → 면적 0.0 (유효한 구간)
  [3, -3] → [3, 2] : a > end   → 뒤집힌 구간 → -1

★ 헷갈린 원인: "점의 개수(6)"와 "횟수(5)"를 구분하지 않은 것.
  len(seq) 가 아니라 len(seq) - 1 이 n 이다.
  (실수 패턴 10번 계열: len 과 인덱스/횟수 기준의 불일치)

------------------------------------------------------------------------------
✅ 잘한 것
------------------------------------------------------------------------------
1. 사다리꼴 면적을 area 리스트로 미리 쌓아둔 설계.
   구간 질의를 sum(area[a:end]) 한 줄로 끝낼 수 있게 만들었다.
2. 슬라이스 끝을 end(미포함)로 잡은 것.
   x=a~end 구간의 사다리꼴은 인덱스 a..end-1 이므로 정확하다.
3. 폭 0 케이스를 특별 처리하지 않은 것.
   area[a:a] 가 빈 슬라이스 → sum([]) == 0 이 자동으로 나온다.
   "예외를 if 로 막지 말고 구조로 없애기"의 좋은 예 (실수 패턴 12번).

------------------------------------------------------------------------------
⚠️ 고칠 것 — 우연히 안 터지는 코드 2개
------------------------------------------------------------------------------
[1] 카운터 i 가 죽은 코드
      i = 0 / i += 1 로 횟수를 세지만 어디에서도 쓰이지 않는다.
      n = len(temp) - 1 로 구했으므로 불필요.

      게다가 바로 아래 리스트 컴프리헨션에서 같은 이름 i 를 다시 쓴다.
      Python 3 는 컴프리헨션 스코프가 분리되어 있어 우연히 안 터진다.
      Python 2 였다면 while 의 i 가 덮어써졌다.
      → 우연히 안 터지는 코드는 "왜 안 터지는지" 증명해야 한다.
        증명이 필요한 구조를 애초에 만들지 않는 게 정석. (실수 패턴 11번)

[2] 파라미터 k 를 루프 변수로 덮어씀
      while 안에서 k = k//2 로 파라미터를 소비 → 원래 초항이 사라진다.
      이 문제에서는 초항을 다시 쓰지 않으므로 통과하지만,
      "변수가 두 역할을 겸하는" 패턴은 위험하다. (실수 패턴 3번)
      → cur = k 로 복사해 순회하면 초항이 보존된다.

[3] 제출 전 print 제거
      디버깅용 print(temp), print(area) 가 남아 있었다.

------------------------------------------------------------------------------
💡 더 나아간 최적화 (이 문제에선 불필요)
------------------------------------------------------------------------------
질의가 많고 구간이 길면 누적합으로 O(1) 질의가 가능하다.

    prefix = [0]
    for a in area:
        prefix.append(prefix[-1] + a)
    # 구간 [a, end] 의 정적분 = prefix[end] - prefix[a]

이 문제는 구간 길이가 200 이하로 제한되어 sum 으로도 충분하다.
⚠️ 누적합을 쓸 때는 prefix[l-1] 에서 l=0 인 경우(빈 prefix)를 주의해야 한다
   → 위처럼 prefix 앞에 0 을 하나 깔면 가드가 필요 없어진다. (실수 패턴 13번)
"""


# =============================================================================
# 4. 검증
# =============================================================================

def brute(k, ranges):
    """좌표를 직접 만들고 구간마다 사다리꼴을 하나씩 더함 (대조용)."""
    seq = [k]
    cur = k
    while cur > 1:
        cur = cur // 2 if cur % 2 == 0 else cur * 3 + 1
        seq.append(cur)
    n = len(seq) - 1

    out = []
    for a, b in ranges:
        end = n + b
        if a > end:
            out.append(-1)
            continue
        total = 0.0
        for x in range(a, end):
            total += (seq[x] + seq[x + 1]) / 2
        out.append(total)
    return out


if __name__ == "__main__":
    import random

    # 문제 예제 (k=5, n=5)
    #   [0, 0]  → 전체 구간 [0, 5]
    #   [2, -3] → [2, 2] → 0.0
    #   [3, -3] → [3, 2] → -1
    got = solution(5, [[0, 0], [0, -1], [2, -3], [3, -3]])
    print("k=5 결과:", got)
    assert got[2] == 0.0, "폭 0 구간은 0.0"
    assert got[3] == -1, "뒤집힌 구간은 -1"

    # 전체 구간 = 사다리꼴 전체 합
    seq5 = [5, 16, 8, 4, 2, 1]
    expected_all = sum((seq5[i] + seq5[i + 1]) / 2 for i in range(5))
    assert got[0] == expected_all

    # 제출 코드와 개선 코드가 같은 답을 내는지
    random.seed(0)
    mismatch = 0
    for _ in range(2_000):
        k = random.randint(2, 10_000)
        rs = [[random.randint(0, 30), -random.randint(0, 30)] for _ in range(5)]
        a = solution(k, [r[:] for r in rs])
        b = solution_submitted(k, [r[:] for r in rs])
        c = brute(k, [r[:] for r in rs])
        if not (a == b == c):
            mismatch += 1
            print("MISMATCH:", k, rs, a, b, c)
    print(f"3-way 대조 불일치: {mismatch}건")

    # 경계
    assert solution(2, [[0, 0]]) == [1.5]        # 2 ⇒ 1 (n=1), 사다리꼴 (2+1)/2
    assert solution(2, [[1, 0]]) == [0.0]        # [1, 1] → 폭 0 → 0.0
    assert solution(2, [[1, -1]]) == [-1]        # [1, 0] → a > end → -1
    print("경계 확인:", solution(2, [[0, 0], [1, 0], [1, -1]]))
