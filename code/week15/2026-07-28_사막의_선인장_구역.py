def brute(m, n, h, w, drops):
    """모든 후보 구역을 직접 훑어 최솟값 계산 — 느리지만 정답 보장."""
    INF = float('inf')
    t = [[INF] * n for _ in range(m)]
    for idx, (r, c) in enumerate(drops):
        if t[r][c] == INF:
            t[r][c] = idx

    best = -1
    ans = None
    for i in range(m - h + 1):
        for j in range(n - w + 1):
            v = min(t[a][b] for a in range(i, i + h) for b in range(j, j + w))
            if v > best:
                best = v
                ans = [i, j]
    return ans


