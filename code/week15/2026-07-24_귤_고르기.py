"""
==============================================================================
 프로그래머스 Lv2 - 귤 고르기
 날짜: 2026-07-24 (Week 15)
 분류: 정렬 + 그리디 (Counter 빈도 내림차순 누적)
==============================================================================

[문제 설명]
경화는 수확한 귤 중 k개를 골라 상자 하나에 담아 판매하려고 한다.
귤을 크기별로 분류했을 때 "서로 다른 종류의 수"를 최소화하고 싶다.

예) 귤 8개의 크기가 [1, 3, 2, 5, 4, 5, 2, 3] 이고 k = 6 이면
    크기 1, 4인 귤을 제외하고 담을 때 종류가 {2, 3, 5} 로 3가지 → 최소값 3

k와 tangerine 배열이 주어질 때, 크기가 서로 다른 종류 수의 최솟값을 return.

[제한사항]
    1 <= k <= len(tangerine) <= 100,000
    1 <= tangerine의 원소 <= 10,000,000

[핵심 아이디어 ★]
    개수가 많은 크기부터 담는다.
    → 종류 수를 t로 고정했을 때 k개를 채울 수 있는지는
      "상위 t개 종류의 개수 합 >= k" 로 결정된다.
      상위 t개의 합은 어떤 t개 조합보다도 크므로,
      이걸로 못 채우면 어떤 조합으로도 못 채운다.
    → 따라서 큰 것부터 누적해 k를 처음 넘기는 지점이 정답.
      (교환 논증(exchange argument) 형태의 그리디 정당성)

[시간복잡도]
    Counter 생성        O(n)
    most_common() 정렬  O(m log m)     m = 서로 다른 크기의 개수 (m <= n)
    누적 순회           O(m)
    ------------------------------------
    총 O(n log n),  n = 100,000 → 여유롭게 통과 (실측 0.14s)

    ※ most_common()은 인자를 안 주면 "전체를 정렬"한다. 부분정렬 아님.
==============================================================================
"""

from collections import Counter


# =============================================================================
# 1. 제출 코드 (통과)
# =============================================================================

def solution_submitted(k, tangerine):
    answer = 0
    t_count = Counter(tangerine).most_common()   # [(크기, 개수), ...] 개수 내림차순
    i = 0
    while i <= len(tangerine):                   # ⚠️ 문제 지점 (아래 피드백 2번)
        if k - t_count[i][1] > 0:                # ✅ 잘한 지점 (아래 피드백 1번)
            k = k - t_count[i][1]                # 남은 개수 차감
            answer += 1                          # 종류 하나 소비
            i += 1
        else:                                    # k - cnt <= 0 → 이 종류로 다 채움
            answer += 1
            break
    return answer


# =============================================================================
# 2. 피드백
# =============================================================================
"""
------------------------------------------------------------------------------
✅ 잘한 것 — 부등호 `> 0` 을 정확히 잡음
------------------------------------------------------------------------------
이 문제의 유일한 함정.

    k == cnt 인 순간 (남은 개수가 딱 떨어짐)
      `> 0`  → 조건 거짓 → else 로 빠짐 → answer += 1 하고 break → 정답
      `>= 0` → 조건 참   → k = 0 인 채로 다음 반복 진입
               → 다음 종류를 하나 더 세어버림 → +1 오답

반복 실수 목록 1순위가 "부등호 방향 (< vs <=, > vs >=)" 인데 이번엔 정면으로 뚫었음.


------------------------------------------------------------------------------
⚠️ 고칠 것 — while 조건이 두 군데 동시에 틀림
------------------------------------------------------------------------------

    while i <= len(tangerine):

    (1) 순회 대상과 범위 기준이 다름
        i 는 t_count (종류 개수 m) 를 인덱싱하는데
        한계값은 tangerine (원소 개수 n).
        m <= n 이라 우연히 안 걸릴 뿐, 논리적으로 무관한 두 리스트다.
        → 인덱싱하는 리스트와 len()의 대상은 반드시 같아야 함.

    (2) `<=` 는 인덱스 범위 밖
        원소가 4개면 len == 4, 유효 인덱스는 0~3.
        i == len(...) 은 이미 IndexError 구간.
        → len 기준이면 `<`, 마지막 인덱스 기준이면 `<=`

    올바른 형태:  while i < len(t_count):
                        ↑ 대상       ↑ 부등호   둘 다 바꿔야 함

    ※ 대상만 바꾸고 `<=` 를 두면 오히려 더 위험하다.
      기존엔 len(tangerine)이 커서 우연히 안 걸렸는데,
      t_count로 줄이면 딱 경계에 닿는다.


------------------------------------------------------------------------------
🤔 그런데 왜 원래 코드는 안 터졌나 — "죽은 조건"의 증명
------------------------------------------------------------------------------
    불변식:  루프 진입 시점에  (남은 개수들의 합 S) >= (남은 k)  가 항상 성립

    - 처음:   S = n >= k          (제한사항이 보장)
    - 이후:   양쪽에서 같은 cnt 를 빼므로 부등식 유지
    - 마지막 원소에 도달하면 S = cnt >= k  →  k - cnt <= 0  →  break

    즉 while 조건은 절대 평가되지 않는다.
    이걸 설명할 수 있으면 "안전이 보장된 코드",
    설명 못 하면 "우연히 통과한 코드".
    → 애초에 증명이 필요한 구조를 안 만드는 게 낫다. (아래 개선 코드)


------------------------------------------------------------------------------
📌 체크리스트로 굳히기 — 인덱스 루프를 쓸 때는 항상 두 개를 세트로
------------------------------------------------------------------------------
    1. 범위 기준이 "지금 인덱싱하고 있는 그 리스트" 인가?
         t_count[i] 를 쓰면 한계도 len(t_count)
    2. `<` 인가 `<=` 인가?
         len 기준 → `<`  /  마지막 인덱스 기준 → `<=`

    (실수 패턴 목록의 "탐색 범위 산정" 과 "부등호 방향" 이 겹친 케이스.
     하나만 고치면 안 됨.)
"""


# =============================================================================
# 3. 개선 코드
# =============================================================================

def solution(k, tangerine):
    """인덱스 변수 · 죽은 조건 · 범위 걱정을 전부 제거한 버전."""
    answer = 0
    for cnt in sorted(Counter(tangerine).values(), reverse=True):
        k -= cnt
        answer += 1
        if k <= 0:
            break
    return answer


# 개선 포인트
#   - 인덱스 순회 대신 값 순회 → 범위 실수 원천 차단
#     (실수 패턴: "인덱스 순회보다 언패킹")
#   - most_common() 대신 .values() 정렬 → 크기 값은 안 쓰므로 튜플이 불필요
#   - 종료 조건이 break 하나로 명시 → "왜 안 터지나"를 증명할 필요가 사라짐


# =============================================================================
# 4. 검증 (브루트포스 대조)
# =============================================================================

def brute(k, tangerine):
    """종류 수를 1부터 늘려가며 상위 t개 합이 k 이상이 되는 첫 지점."""
    counts = sorted(Counter(tangerine).values(), reverse=True)
    total = 0
    for t, c in enumerate(counts, start=1):
        total += c
        if total >= k:
            return t


if __name__ == "__main__":
    import random
    import time

    # 예제
    assert solution(6, [1, 3, 2, 5, 4, 5, 2, 3]) == 3
    assert solution_submitted(6, [1, 3, 2, 5, 4, 5, 2, 3]) == 3

    # 경계 케이스
    assert solution(1, [7]) == 1                    # 원소 1개
    assert solution(5, [1, 1, 1, 1, 1]) == 1        # 전부 같은 크기
    assert solution(5, [1, 2, 3, 4, 5]) == 5        # 전부 다른 크기

    # 랜덤 대조 20,000회
    random.seed(0)
    mismatch = 0
    for _ in range(20_000):
        n = random.randint(1, 12)
        tg = [random.randint(1, 4) for _ in range(n)]
        k = random.randint(1, n)
        if solution(k, list(tg)) != brute(k, list(tg)):
            mismatch += 1
            print("MISMATCH:", k, tg)
    print(f"랜덤 대조 불일치: {mismatch}건")

    # 성능 (최대 입력)
    n = 100_000
    big = [random.randint(1, 10_000_000) for _ in range(n)]
    start = time.time()
    solution(n, big)
    print(f"n=100,000 실행시간: {time.time() - start:.3f}s")
