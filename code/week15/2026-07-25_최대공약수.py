"""
==============================================================================
 프로그래머스 Lv2 - 최대공약수 (카드 나눠 갖기)
 날짜: 2026-07-25 (Week 15)
 분류: 수론 (GCD) + 후보 축소
==============================================================================

[문제 설명]
철수와 영희가 카드를 절반씩 나눠 갖고, 다음 두 조건 중 하나를 만족하는
가장 큰 양의 정수 a를 구한다.

  조건1: 철수 카드 전부를 a로 나눌 수 있고, 영희 카드는 하나도 못 나눔
  조건2: 영희 카드 전부를 a로 나눌 수 있고, 철수 카드는 하나도 못 나눔

만족하는 a가 없으면 0.

예) A=[10,20], B=[5,17] → a=10
    (10이 10·20을 나누고, 5·17은 못 나눔)

[핵심 통찰 — 후보는 딱 2개 ★]
    조건1을 만족하는 a는 반드시 A 전부를 나눈다 → a는 gcd(A)의 약수 → a <= gcd(A).
    "가장 큰 a"를 원하므로 후보 1순위는 gcd(A) 자기 자신.

    gcd(A)가 실패(=영희 카드를 나눔)하면, 그 약수들은 볼 필요 없다.
    약수는 원래 수가 나누는 걸 전부 나누므로, gcd(A)가 B를 나눴다면
    그 약수도 나눌 위험만 커지고 크기는 더 작다. → 검사 가치 없음.

    ∴ 검사할 후보는 gcd(A), gcd(B) 두 개뿐.
      약수 나열도, 배수 순회도 필요 없다.

[두 번째 함정 — "나눈다" ≠ "서로소가 아니다"]
    "gcd(A)가 B를 안 나눈다" 를  gcd(gcd(A), gcd(B)) == 1  로 판정하면 틀림.

    반례) A=[4], B=[6]
      실제:  4가 6을 나누나? 6 % 4 = 2 → 안 나눔 → 조건 만족
      오판:  gcd(4, 6) = 2 ≠ 1 → "서로소 아님" → 불만족으로 잘못 판정
      → 정반대 결론.

    "a가 b를 나눈다"(b % a == 0) 와 "a, b가 서로소"(gcd==1) 는 다른 관계다.
    공약수가 있어도(4,6은 2 공유) 나누어떨어지지 않을 수 있다.
    → 올바른 검사는 b를 하나씩 직접 나눠보는 것:  all(b % gcdA != 0 for b in B)

    ※ 방향 주의: a가 b를 나누는 것이므로 b % a,  gcdA % b 아님.

[시간복잡도]
    gcd(A) = reduce(gcd, A)   O(n log M)     M = 최대 원소값 (유클리드 호제법)
    gcd(B)                    O(n log M)
    B / A 나눔 검사           O(n)
    ------------------------------------
    총 O(n log M)   ← "O(3n)" 이 아니라 O(n log M).
                       상수배는 빅오에서 떨어지고, gcd의 log 비용은 남는다.
    실측: n=500,000 에서 0.024s
==============================================================================
"""

from math import gcd
from functools import reduce


# =============================================================================
# 제출 코드 (통과)
# =============================================================================

def solution(arrayA, arrayB):
    answer = 0
    gcda = reduce(gcd, arrayA)          # A 전부를 나누는 최대 수
    gcdb = reduce(gcd, arrayB)          # B 전부를 나누는 최대 수

    # 조건1: gcda 가 B 를 하나도 안 나눔  (A 를 나누는 건 자동 → 검사 불필요)
    if all(b % gcda != 0 for b in arrayB):
        answer = max(answer, gcda)

    # 조건2: gcdb 가 A 를 하나도 안 나눔
    if all(a % gcdb != 0 for a in arrayA):
        answer = max(answer, gcdb)

    return answer


# =============================================================================
# 피드백 — 대화에서 나온 실수들
# =============================================================================
"""
------------------------------------------------------------------------------
막혔던 지점 & 실수 (제출 전 초안 → 수정)
------------------------------------------------------------------------------

[1] 조건 방향이 뒤집힘
    초안:  if all(a % gcda != 0 for a in arrayA) and all(b % gcdb == 0 for b in arrayB)
    문제:  gcda 는 A 전부를 나누라고 구한 값인데 "A 를 안 나눈다"(!= 0)를 검사.
           gcd 정의상 항상 거짓 → 조건이 절대 성립 안 함.
    교훈:  검사해야 하는 건 "gcda 가 B 를 안 나눔" 하나뿐.
           A 를 나누는지는 gcd 라서 자명 → 볼 필요 없음.

[2] 마지막 줄이 조건을 통째로 무시 ★ (사용자가 스스로 발견: "없는 case가 빠졌다")
    초안:  answer = max(gcda, gcdb)   ← candA/candB 정해놓고 안 씀
    문제:  조건 만족 여부와 무관하게 무조건 gcd 중 큰 값을 반환.
           두 조건 다 실패해도 0 이 안 나옴.
    교훈:  answer=0 에서 시작 → 조건 통과한 것만 max 로 갱신.
           둘 다 실패하면 0 이 그대로 남아 "없는 case"가 공짜로 처리됨.
           (실수 패턴 4번: 덮어쓰기 vs 누적 — max 누적이 핵심)

[3] elif → if 두 개
    초안:  if ... elif ...
    문제:  두 조건이 동시에 성립할 수 있는데 elif 는 하나만 검사.
           그리고 candA/candB 가 둘 다 미성립 시 초기화 안 돼 NameError 위험.
    교훈:  독립 조건은 독립된 if 로. 후보는 0 으로 미리 깔아둔다.

[4] "나눈다" 와 "서로소" 혼동 (위 함정 섹션)
    gcd(gcda, gcdb) == 1 로 판정하려다 A=[4],B=[6] 반례로 기각.
    b % gcda != 0 로 직접 검사하는 게 정답.

------------------------------------------------------------------------------
reduce 복습
------------------------------------------------------------------------------
    reduce(gcd, [10,20,5]) = gcd(gcd(10,20), 5) = gcd(10,5) = 5
    리스트를 이항 연산으로 왼쪽부터 접어 하나의 값으로 만든다.

    동치 for문:
        acc = arr[0]
        for x in arr[1:]:
            acc = gcd(acc, x)

    ⚠️ 빈 리스트면 터짐 → 초기값 필요:  reduce(gcd, arr, 0)
       (gcd 에서 0 은 항등원: gcd(0, x) == x)
       이 문제는 카드를 절반씩 나눠 배열이 비지 않으므로 초기값 생략 가능.
"""


# =============================================================================
# 검증 (브루트포스 대조)
# =============================================================================

def brute(A, B):
    """1부터 최대값까지 전부 시도 — 느리지만 정답 보장 (대조용)."""
    best = 0
    hi = max(max(A), max(B))
    for a in range(1, hi + 1):
        c1 = all(x % a == 0 for x in A) and all(y % a != 0 for y in B)
        c2 = all(y % a == 0 for y in B) and all(x % a != 0 for x in A)
        if c1 or c2:
            best = max(best, a)
    return best


if __name__ == "__main__":
    import random
    import time

    # 예제
    assert solution([10, 20], [5, 17]) == 10

    # 경계
    assert solution([7], [7]) == 0            # 같은 수 → 둘 다 상대를 나눔 → 0
    assert solution([1], [2]) == 2            # gcdb=2 가 1 안 나눔
    assert solution([2, 4], [8, 16]) == 8     # B쪽 gcd 8 이 A 안 나눔

    # 랜덤 대조 30,000회
    random.seed(1)
    mismatch = 0
    for _ in range(30_000):
        n = random.randint(1, 4)
        A = [random.randint(1, 30) for _ in range(n)]
        B = [random.randint(1, 30) for _ in range(n)]
        if solution(A, B) != brute(A, B):
            mismatch += 1
            print("MISMATCH:", A, B)
    print(f"랜덤 대조 불일치: {mismatch}건")

    # 성능 (최대 규모)
    n = 500_000
    A = [random.randint(1, 10**8) for _ in range(n)]
    B = [random.randint(1, 10**8) for _ in range(n)]
    start = time.time()
    solution(A, B)
    print(f"n=500,000 실행시간: {time.time() - start:.3f}s")
