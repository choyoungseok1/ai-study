"""
점 찍기 (프로그래머스 Lv2) — 격자점 개수 세기 + 정수 제곱근

[문제]
2차원 좌표평면에서 두 양의 정수 k, d가 주어질 때:
- 원점(0,0)에서 x축 방향 a*k, y축 방향 b*k (a,b = 0,1,2,...) 위치에 점을 찍음
- 단, 원점과의 거리가 d를 넘으면(> d) 찍지 않음  →  x² + y² ≤ d²
- 총 몇 개 찍히는지 return

예) k=2, d=4 → (0,0),(0,2),(0,4),(2,0),(2,2),(4,0) = 6개

제한: 1 ≤ k ≤ 1e6, 1 ≤ d ≤ 1e6

[복잡도 — 먼저 따진 것]
순진하게 이중 루프(x 후보 × y 후보)로 x²+y²≤d² 검사하면:
  k=1일 때 x 후보 d/k = 1e6개, y도 1e6개 → 1e12. 죽음.
  ('큰 입력(1e6)에 O(n²) 금지')
→ x 루프 하나만 돌고(O(d/k)), 각 x마다 가능한 y 개수를 O(1)로 계산.
  전체 O(d/k).

[핵심 — y 개수를 루프 없이 세기]
x를 하나 고정하면 y 조건은:
  x² + y² ≤ d²  →  y ≤ √(d² - x²)   그리고 y는 k의 배수(y = b*k)
그러니:
  y_max = √(d² - x²)          # y가 넘을 수 없는 실제 최댓값
  개수   = y_max // k + 1       # 그 안의 k 배수 개수 (b=0 포함이라 +1)

주의 (자주 틀리는 순서):
  d² - x² 은 y²의 상한이지 y의 상한이 아니다.
  반드시 √ 를 먼저 씌워 y의 상한으로 바꾼 뒤 //k 로 개수를 센다.
  ((d²-x²)/k 처럼 제곱근 없이 나누면 틀림)

[부동소수점 함정]
√ 를 math.sqrt 로 하면 반환이 float라 정밀도 오차.
  d=1e6이면 d²=1e12 — 이 크기에서 sqrt는 경계에서 어긋나
  (딱 떨어지는 제곱수인데 1999.9999... 로 나와 하나 누락).
→ math.isqrt 사용. isqrt(n) = ⌊√n⌋ 을 정확히 정수로 반환.
  이미 정수라 floor 불필요, //k 도 정수 나눗셈이라 floor 자동.
"""

from math import isqrt


def solution(k, d):
    tot_num = 0
    for x in range(0, d + 1, k):
        y_max = isqrt(d ** 2 - x ** 2)   # ⌊√(d²-x²)⌋ 정확히
        tot_num += y_max // k + 1        # 0..y_max 안의 k 배수 개수 (b=0 포함)
    return tot_num


if __name__ == "__main__":
    print(solution(2, 4))   # 6
    print(solution(1, 5))   # 원점 거리 ≤5 인 격자점 개수


