"""
디펜스 게임 (프로그래머스 Lv2) — min heap 그리디

[문제]
병사 n명으로 연속된 적의 공격을 순서대로 막는다.
- 매 라운드 enemy[i]마리 등장, 남은 병사 중 enemy[i]명 소모해 막음
- 남은 병사보다 적이 많으면 게임 종료
- 무적권: 병사 소모 없이 한 라운드 막음, 최대 k번
- 몇 라운드까지 막을 수 있는지 return (전부 막으면 len(enemy))

제한: n ≤ 1e9, k ≤ 5e5, len(enemy) ≤ 1e6, enemy[i] ≤ 1e6

[핵심 통찰 — 무적권을 어디에 쓰나]
"큰 라운드를 미리 골라 무적권 확정"은 틀림.
  반례: n=3, k=1, enemy=[1,1,1,1,4]
        4를 미리 무적권으로 잡으면 앞의 1,1,1 막다가 3-1-1-1=0,
        4번째 1에서 죽어 4에 도달도 못함.
→ 미리 확정하지 말고, 진행하면서 "일단 무적권으로 막았다 치고" 큐에 넣는다.
  무적권 사용이 k를 초과하면, 지금까지 무적권으로 막은 것 중
  "가장 작은 값"을 병사로 되돌린다(n에서 뺌).
  => 무적권은 결국 큰 값들에만 남게 되어 병사 소모가 최소화됨 (그리디 최적).

[자료구조] 최솟값을 반복해서 꺼내는 연산 → min heap (heapq).
  연산→구조 매핑: "최솟값/최댓값 계속 꺼냄", "top k 유지", "우선순위" → heap

[복잡도] 라운드마다 push/pop 각 O(log k) → 전체 O(len(enemy) · log k)
  10^6 · log(5e5) ≈ 2천만. 통과. (라운드당 재검색 O(n²)면 죽음)

[경계 조건]
- 막을 수 있는 조건은 n >= enemy[i] (병사=적이면 막음). 종료는 n < enemy[i].
  → 판정은 n < 0 (n <= 0 아님. 병사 0명은 아직 안 죽음)
- return i (i+1 아님): n<0 = 인덱스 i 라운드를 못 막음 = 직전까지 i개(0..i-1) 막음.
  0-indexed라 "인덱스 i에서 사망 → i개 방어"가 딱 맞음.
"""

import heapq


def solution(n, k, enemy):
    heap = []
    for i in range(len(enemy)):
        # 이번 라운드 적 수를 heap에 넣기 (일단 무적권으로 막았다고 가정)
        heapq.heappush(heap, enemy[i])
        # 무적권 사용 횟수(k)를 초과하면,
        # 지금까지 무적권으로 막은 것 중 가장 작은 값을 병사로 되돌린다
        if len(heap) > k:
            n -= heapq.heappop(heap)
            # 병사가 부족하면 이번 라운드(i)를 못 막음 → 직전까지 i개 막음
            if n < 0:
                return i
    # break 없이 끝까지 왔으면 = 모든 라운드 방어 성공
    return len(enemy)


if __name__ == "__main__":
    # 프로그래머스 예시
    print(solution(7, 3, [4, 2, 4, 5, 3, 3, 1]))   # 5
    print(solution(2, 4, [3, 3, 3, 3]))            # 4

    # 대화 중 만든 반례 (큰 값 미리 확정 금지 검증)
    print(solution(3, 1, [1, 1, 1, 1, 4]))         # 5


