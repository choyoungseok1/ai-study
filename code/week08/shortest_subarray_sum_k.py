"""
프로그래머스 Lv2 - 연속된 부분 수열의 합

[문제 요약]
- 비내림차순으로 정렬된 수열 sequence와 정수 k가 주어진다.
- 연속된 부분 수열(임의의 두 인덱스와 그 사이를 모두 포함)의 합이 k인 것 중:
    1) 길이가 가장 짧은 것
    2) 길이가 같으면 시작 인덱스가 작은 것
  의 [시작 인덱스, 끝 인덱스]를 return. (인덱스는 0부터)

[제한사항]
- 5 ≤ len(sequence) ≤ 1,000,000      → O(n²)는 ~10¹² → TLE. O(n) 필요.
- 1 ≤ 원소 ≤ 1,000  (모두 양수)        → 합이 단조 → 투포인터 성립
- 5 ≤ k ≤ 1,000,000,000  (항상 만들 수 있음)

[핵심: 투포인터(슬라이딩 윈도우) — O(n)]
- 원소가 모두 양수라 윈도우를 넓히면 합↑, 좁히면 합↓ (단조).
  → left/right 두 포인터로:
     합 < k  : right 확장 (더하기)
     합 > k  : left 축소 (왼쪽 원소 '빼기')   ← '리셋(0)'이 아니라 '빼기'가 핵심 (O(n))
     합 == k : 후보 기록 후 left 축소 (다음 윈도우 탐색)
  - 두 포인터가 둘 다 앞으로만 → 전체 O(n).
- 답 갱신: 더 짧을 때만(strict <) → "짧은 것 + 같으면 앞선 것"이 자동
  (투포인터는 시작 인덱스 증가 순으로 후보를 찾으므로).
"""


def solution(sequence, k):
    answer = 0                          # answer = 현재 윈도우 [left, right-1]의 합
    left, right = 0, 0                  # right = '다음에 더할' 인덱스 → 윈도우 끝은 right-1
    best_len = float('inf')
    while True:
        if answer < k:
            if right == len(sequence):      # 더 못 늘리는데 아직 부족 = 진짜 끝
                break
            answer += sequence[right]       # 오른쪽 확장
            right += 1
        elif answer > k:
            answer -= sequence[left]        # 왼쪽 축소 (리셋 X)
            left += 1
        else:                               # answer == k : 후보 발견
            new_len = right - left          # 윈도우 [left, right-1]의 길이
            if new_len < best_len:          # strict '<' → 짧은 것, 같으면 먼저(앞선) 것 유지
                best_len = new_len
                best_start, best_end = left, right - 1
            answer -= sequence[left]        # 기록 후 왼쪽 빼서 다음 윈도우로
            left += 1
    return [best_start, best_end]


# ---------------------------------------------------------------------------
# 피드백 (풀이 과정 회고)
# ---------------------------------------------------------------------------
# [핵심]
#  - 제한부터: n ≤ 10⁶ → 이중 루프(O(n²))는 ~10¹² → TLE.
#    원소가 모두 양수 + 정렬 → 합 단조 → 투포인터(O(n))가 정답.
#
# [순서대로 잡은 버그들]
#  1. '리셋' 방식: 합 ≥ k일 때 answer=0으로 초기화하고 시작점부터 다시 → 시작점마다
#     재탐색 = O(n²) → TLE.  수정: 리셋 대신 '왼쪽 원소 빼기'(투포인터).
#  2. IndexError: sequence[i+n]에서 오른쪽 끝이 범위를 넘음.
#     수정: 오른쪽 끝 인덱스를 항상 len 미만으로 가드.
#  3. off-by-one: sequence[right]를 더한 '뒤에' right += 1 → 현재 합의 윈도우는
#     [left, right-1].  그래서 new_len = right-left, end = right-1 (둘 다 -1 보정).
#  4. 무한루프: 합 == k 분기에서 포인터를 안 움직여 같은 상태가 반복됨.
#     수정: 기록 후 왼쪽 빼고 left += 1.
#  5. 루프 조기 종료: `while right < len`이 right가 끝에 닿는 순간 죽어서,
#     '왼쪽만 줄이면 나오는 마지막 윈도우'를 놓침. (여기서 한참 헤맴)
#     수정: while True + (합 < k 이고 right == len 일 때만 break).
#
# [재사용 패턴]
#  - 연속 부분합 + 양수 → 투포인터: 합 부족=오른쪽 확장, 합 초과=왼쪽 축소.
#    핵심은 '리셋(0)'이 아니라 '왼쪽 한 개 빼기'. right가 지난 곳을 다시 안 감 → O(n).
#  - 종료 조건: "확장도 못 하고(right==끝) 아직 부족할 때"만 끝낸다.
#    (right==끝이어도 '축소'로 찾을 윈도우가 남아 있을 수 있음)
#  - 최단 + 최선두 선택: strict '<' 로만 best 갱신 ('=='나 '>'로 갱신하면 '앞선 것' 깨짐).
#
# [복잡도] 시간 O(n), 공간 O(1).


if __name__ == "__main__":
    print(solution([1, 2, 3, 4, 5], 5))   # [4, 4]  (5 하나, 길이 1)
    print(solution([1, 2, 3, 4, 5], 7))   # [2, 3]  (3+4)
    print(solution([5, 5, 5], 5))         # [0, 0]  (길이 1 중 앞선 것)
    print(solution([1, 1, 1, 2, 3], 3))   # [4, 4]  (3 하나가 1+2보다 짧음)
