"""
프로그래머스 Lv2 - 아날로그 시계 (초침 알람 횟수 세기)

[문제 요약]
- 시침은 12시간, 분침은 60분, 초침은 60초마다 시계를 한 바퀴 돈다.
- 초침이 시침 또는 분침과 겹칠 때마다 알람이 울린다.
- 단, 0시/12시 정각처럼 세 바늘이 동시에 겹칠 때는 알람이 1번만 울린다.
- h1:m1:s1 부터 h2:m2:s2 까지(양 끝 포함) 알람이 울린 횟수를 return.

[제한사항]
- 0 <= h1, h2 <= 23 / 0 <= m1, m2 <= 59 / 0 <= s1, s2 <= 59
- h1:m1:s1 < h2:m2:s2 (자정을 넘겨 0시로 되돌아가는 입력은 없음)

[핵심 아이디어]
- 겹치는 시각은 정수 초가 아니다(예: 6분 0.501초) → '같은지' 직접 비교하면 놓침.
- 대신 1초 구간 [t, t+1]에서 초침이 다른 바늘을 '추월'했는지로 탐지.
- 초침-분침/초침-시침의 1초당 상대 회전량이 360° 미만(각각 354°, 359.5°)이라
  한 구간에 같은 쌍의 겹침은 최대 1번 → 1초 간격 탐지가 안전하다.
"""


def solution(h1, m1, s1, h2, m2, s2):
    answer = 0

    # 시작/종료 시각을 '초' 단위로 변환
    start_time = h1 * 3600 + m1 * 60 + s1
    end_time = h2 * 3600 + m2 * 60 + s2

    # 특정 '초'에서 시침/분침/초침의 각도 반환 (12시간 = 43200초 주기)
    def get_angles(total_seconds):
        h_angle = (total_seconds % 43200) * (360 / 43200)
        m_angle = (total_seconds % 3600) * (360 / 3600)
        s_angle = (total_seconds % 60) * (360 / 60)
        return h_angle, m_angle, s_angle

    # 시작 시각에 딱 겹치는 경우는 아래 루프의 첫 구간 [start, start+1]이
    # 왼쪽 '<=' 조건으로 자동으로 잡아주므로 별도 처리 불필요.

    # 1초씩 진행하며 [t, t+1] 구간에서 초침이 다른 바늘을 추월하는지 확인
    for t in range(start_time, end_time):
        h_curr, m_curr, s_curr = get_angles(t)
        h_next, m_next, s_next = get_angles(t + 1)

        # 다음 초에 각도가 0이면 360으로 보정 (354 -> 0 을 354 -> 360 으로 인식)
        if s_next == 0: s_next = 360
        if m_next == 0: m_next = 360
        if h_next == 0: h_next = 360

        # 초침이 시침/분침을 추월: 현재는 이하(<=), 다음은 초과(>)
        # 오른쪽만 strict(>)로 두어, 정수 초에 딱 겹치는 순간이
        # 인접한 두 구간에서 '중복'으로 세어지지 않게 한다(소속을 유일하게).
        match_h = (s_curr <= h_curr and s_next > h_next)
        match_m = (s_curr <= m_curr and s_next > m_next)

        if match_h and match_m:
            # 둘 다 추월한 경우
            #  - 시침·분침이 같은 자리(삼중겹침, 사실상 12:00:00) → 1번
            #  - 서로 다른 자리(서로 다른 순간에 따로 추월)       → 2번
            if h_curr == m_curr:
                answer += 1
            else:
                answer += 2
        elif match_h or match_m:
            answer += 1

    # 종료 시각에 '정확히' 겹치는 경우는 루프가 못 잡는다.
    # (정수 초 겹침은 [t, t+1] 구간에 귀속되는데 [end, end+1] 구간은 루프에 없음)
    # s == h or s == m 한 줄이면 삼중겹침(12:00:00)도 자동으로 1번만 처리됨.
    h_end, m_end, s_end = get_angles(end_time)
    if s_end == h_end or s_end == m_end:
        answer += 1

    return answer


