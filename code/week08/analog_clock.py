# [핵심]
#  - 시뮬레이션(매 순간 == 비교) X  →  카운팅 / 추월 탐지 O.
#  - 경계 처리가 이 문제 난이도의 전부였다.
#
# [이번에 나온 반복 실수]
#  1. 경계 산정: 시작/끝 포함 여부, '정수 초 겹침이 어느 구간 소속인가'를
#     처음엔 감으로 갔다가 예시로 역산해서 잡음. (감 X, 근거 O)
#  2. 들여쓰기: end-check 위치가 두 번 어긋남(루프 안/밖).
#  3. 하나 고치다 다른 거 깨기: 삼중겹침 판별식을 고치며 +2를 +1로 바꿔버림,
#     end-check에 불필요한 h_end != m_end 조건을 붙임.
#     → 수정할 때마다 "원래 맞던 케이스를 깨지 않나?" 재검증하는 습관.
#
# [재사용 가능한 패턴]
#  - 정수 격자에서 연속 이벤트 세기: 한 점이 두 구간 경계에 걸리면
#    한쪽 부등호를 strict로 만들어 소속을 유일하게 한다.
#  - 격자 양 끝점(start/end)은 루프가 자동으로 안 잡을 수 있으니 따로 확인.
#  - 회전 좌표계: 초침은 분침 기준 1분에 354°만 돌아 6° 틈이 생긴다
#    → "1바퀴마다 무조건 1번 만남"은 거짓(초침-분침은 시간당 59번).
#  - IVT(중간값 정리)는 '교점이 있으면 탐지'하는 도구이지
#    '항상 교점이 있다'는 보장이 아니다.


