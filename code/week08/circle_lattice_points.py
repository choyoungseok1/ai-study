"""
프로그래머스 Lv2 - 두 원 사이의 정수 좌표 점 개수

[문제 요약]
- 원점이 중심인 서로 다른 크기의 두 원(반지름 r1 < r2)이 주어진다.
- 두 원 "사이" 공간(각 원 위의 점도 포함)에서 x, y가 모두 정수인 점의 개수를 return.
- 즉  r1² ≤ x² + y² ≤ r2²  를 만족하는 정수 점 (x, y)의 수.

[제한사항]
- 1 ≤ r1 < r2 ≤ 1,000,000
  → bounding box 전수조사는 O(r2²) ≈ 10¹² → TLE. O(r2)로 풀어야 함.

[핵심 아이디어]
1. 대칭으로 ×4:
   영역 {x ≥ 0, y ≥ 1}만 세고 ×4 하면 원점만 빼고 평면 전체를 정확히 한 번씩 덮는다.
   (이 영역을 90°씩 4번 회전 → 사분면 4개 + 축 4개를 중복 없이 분배. 원점은 r1≥1이라 항상 제외.)
   → 별도의 '축 보정 항'이 필요 없음.
2. 각 열(고정 x)의 y 개수는 '루프 없이' 정수 제곱근으로 센다 (prefix 빼기):
     (y² ≤ r2²-x² 인 y≥1 개수)  −  (y² < r1²-x² 인 y≥1 개수)
   = isqrt(r2²-x²)  −  isqrt(max(0, r1²-x²-1))
   → 바깥 x 루프 하나만 남아 O(r2).
3. math.isqrt 필수: math.sqrt(float)는 r2²=10¹² 스케일에서 정밀도가 깨져 경계가 1 틀어진다.
"""

import math


def solution(r1, r2):
    count = 0
    for x in range(0, r2 + 1):
        # 이 열(x)에서 r1² ≤ x²+y² ≤ r2² 인 y≥1 의 개수
        count_x = math.isqrt(r2**2 - x**2) - math.isqrt(max(0, r1**2 - x**2 - 1))
        count += count_x
    return 4 * count


# ---------------------------------------------------------------------------
# 피드백 (풀이 과정 회고)
# ---------------------------------------------------------------------------
# [핵심]
#  - 제한부터 보기: r2 ≤ 10⁶ → 이중 루프(O(r2²))면 ~10¹² → TLE.
#    "열마다 세는 O(r2)"가 정답. (실제로 r2=2000에 이미 2.8초였음)
#
# [개념적으로 넘은 고비]
#  1. 대칭 선택: x≥0, y≥1 + ×4 가 (x≥1,y≥1 + 별도 축항)보다 깔끔.
#     90° 회전 ×4가 원점 빼고 평면을 정확히 1번씩 덮어서 축 보정이 자동으로 됨.
#  2. '겹침/경계'가 아니라 '개수'가 핵심 — 한 열의 y 개수를 prefix 빼기로:
#     isqrt(위 경계) − isqrt(아래 경계 미만). (미사일 문제의 [0,end]−[0,start]와 같은 무기)
#  3. 큰 좌표값(10⁶)에 겁먹지 말 것 — 복잡도는 입력 *개수*에 달렸지, 좌표축을 훑는 게 아님.
#
# [구현 함정]
#  1. O(r2²) 이중 루프 → 안쪽 루프를 isqrt 카운트로 대체해 O(r2).
#  2. math.sqrt(float) 금지 → r2²=10¹²에서 정밀도 깨짐. math.isqrt(정확한 정수 제곱근) 사용.
#  3. isqrt에 음수가 들어가지 않게 아래 경계는 max(0, r1²-x²-1)로 클램프.
#     (위 경계 r2²-x²는 x ≤ r2라 항상 ≥ 0이라 클램프 불필요)
#
# [재사용 패턴]
#  - 격자점 세기 / 원·범위 카운팅: 한 영역만 세고 대칭으로 ×k (여기선 ×4).
#  - "범위 안 개수 = (위 경계까지) − (아래 경계 미만)" (prefix 빼기) + isqrt 로 루프 제거.
#  - 정수 제곱근이 필요하면 항상 math.isqrt (float sqrt는 큰 수에서 off-by-one 위험).


if __name__ == "__main__":
    print(solution(2, 3))    # 20
    print(solution(1, 5))    # 80
    print(solution(3, 10))   # 292
    print(solution(1, 2))    # 12
