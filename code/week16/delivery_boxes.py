"""
프로그래머스 Lv2 - 택배상자
2026-08-03 (Week 16)

────────────────────────────────────────────────────────────
[문제]
1..n 번 상자가 번호 순서대로 메인 컨테이너 벨트에 실려 온다.
기사님이 원하는 순서(order)대로 트럭에 실어야 한다.

지금 실을 차례가 아닌 상자는 '보조 벨트'에 보관한다.
보조 벨트는 입구 외 다른 면이 막혀 있어 **마지막에 넣은 것부터** 꺼낸다.
더 이상 원하는 순서대로 실을 수 없으면 거기서 중단.

몇 개를 실을 수 있는가?

예) order = [4, 3, 1, 2, 5]
  1,2,3 보조 벨트에 보관  →  [1,2,3]
  4 도착, 바로 트럭       →  실은 것 1개
  보조 벨트 top이 3       →  트럭   실은 것 2개
  다음 필요한 건 1인데
    보조 벨트 top = 2, 메인 벨트 = 5  →  중단
  답: 2

[제한사항]
  1 ≤ len(order) ≤ 1,000,000
  order 는 1..n 의 순열
────────────────────────────────────────────────────────────
"""


def solution(order):
    answer = 0
    stack = []
    idx = 0                       # order 에서 지금 실어야 할 위치

    for box in range(1, len(order) + 1):
        stack.append(box)                          # 일단 보조 벨트에 넣고
        while stack and stack[-1] == order[idx]:   # 실을 수 있는 만큼 연쇄 배출
            stack.pop()
            answer += 1
            idx += 1

    return answer


# ============================================================
# 복잡도
# ============================================================
# 시간 O(N) — while 이 중첩돼 보이지만 각 상자는 push 1회 / pop 1회뿐.
#             전체 연산 2N → 분할상환 O(N). (단조 스택과 같은 논증)
# 공간 O(N) — 최악(역순 order)에는 전부 스택에 쌓인다
#
# 실측: N=10^6 랜덤 0.59s / 역순(최악) 0.73s


# ============================================================
# 사고 과정 / 피드백
# ============================================================
#
# ── 1. 자료구조는 문제 설명이 알려준다 ─────────────────────
#
#   "가장 마지막에 보관한 상자부터 꺼낸다" = LIFO = 스택.
#   자료구조 선택은 쉬웠고, 진짜 어려운 건 루프 구조였다.
#
#   등장인물이 셋이라 헷갈린다:
#     - 메인 벨트: 1,2,3,... 순서로 온다
#     - 보조 벨트: 스택
#     - 트럭: order 의 몇 번째까지 실었나
#
#
# ── 2. ★ 핵심 선택 — 루프를 뭘 기준으로 도는가 ─────────────
#
#   (가) 메인 벨트 기준 ← 채택
#        1..n 상자를 하나씩 받으면서, 받을 때마다 "지금 실 수 있나?" 확인
#
#   (나) order 기준
#        order 를 앞에서부터 보며 각 상자를 어디서 가져올지 판단
#
#   ★★ (가)를 고르면 **종료 조건을 안 써도 된다.**
#      못 싣는 상황이 오면 while 조건이 자동으로 거짓이 되고,
#      남은 상자는 스택에 계속 쌓이다가 for 가 끝난다.
#      answer 는 이미 정답이므로 "실패"를 감지할 필요가 없다.
#
#      (나)로 짰다면 "여기서 못 가져오면 break" 분기가 필요했다.
#      → 실수 패턴 12번 계열: 예외를 처리하는 게 아니라
#        **예외가 생기지 않는 구조를 고른 것**
#
#   ⚠️ 실수 패턴 1번: "바깥은 뭐 기준, 안쪽은 뭐 기준"을
#      코드 짜기 전에 정한다. 둘 다 풀리지만 안쪽 로직이 완전히 달라진다.
#
#
# ── 3. 왜 if 가 아니라 while 인가 ───────────────────────────
#
#   4번을 받아 트럭에 싣는 순간, 스택 top 이 3번이라 **연달아** 실린다.
#   한 번 실은 뒤에 또 실을 수 있는지 다시 확인해야 하므로 while.
#   if 였다면 [4,3,...] 에서 3을 놓친다.
#
#
# ── 4. `stack and` 를 앞에 둔 이유 ─────────────────────────
#
#   단락 평가(short-circuit). 스택이 비면 stack[-1] 을 평가하지 않는다.
#   순서를 바꾸면 IndexError.
#
#
# ── 5. answer 와 idx 를 왜 따로 두나 (값이 항상 같은데) ─────
#
#   하나로 합칠 수 있지만 **의미가 다르다**:
#     answer = 실은 개수 (결과)
#     idx    = order 에서 지금 볼 위치 (커서)
#   합치는 건 최적화가 아니라 가독성 손해.
#   → 실수 패턴 3번(변수명/의미 혼동) 예방
#
#
# ── 6. ⚠️ idx 범위 초과가 왜 안 나는가 (증명) ──────────────
#
#   order[idx] 에서 idx 가 len(order) 에 도달하면 IndexError.
#   안 나는 이유:
#     - idx 는 pop 할 때만 증가하고, pop 은 push 된 개수를 못 넘는다
#     - push 는 최대 n 번 → idx ≤ n
#     - idx == n 인 시점엔 스택이 비어 있어 `stack and` 에서 걸린다
#
#   ★ 실수 패턴 11번(도달 불가능한 조건).
#      우연히 안 터지는 게 아니라 **왜 안 터지는지 증명 가능해야** 한다.
#      (롤케이크에서도 같은 구조였음 — 마지막 반복이 유효한 절단이
#       아니지만 조건이 성립 불가라 방어됨)
#
#
# ── 7. 등록할 패턴 ──────────────────────────────────────────
#
#   ★ "넣은 순서와 빼는 순서가 다른 문제" = 스택 + 조건 만족 시
#     while 로 연쇄 배출.
#     배출 후 또 배출 가능한지 다시 봐야 하므로 if 가 아니라 while.
#     종료 조건은 별도로 안 쓰고 **루프를 입력 기준으로 돌면 자동 해결.**


# ============================================================
# 테스트  (⚠️ 기대값은 손으로 세고 근거를 남긴다 — 실수 패턴 21번)
# ============================================================
if __name__ == "__main__":
    cases = [
        ([4, 3, 1, 2, 5], 2),   # 문제 예시: 4,3 싣고 중단
        ([5, 4, 3, 2, 1], 5),   # 전부 쌓았다가 역순 배출 → 최악 케이스
        ([1, 2, 3, 4, 5], 5),   # 쌓자마자 바로바로
        ([2, 1, 3], 3),         # 1보관 → 2도착 싣고 → top=1 싣고 → 3
        ([1], 1),
        ([3, 1, 2], 1),         # 1,2보관 → 3도착 싣고 → 다음 1 필요, top=2 → 중단
    ]
    for order, expected in cases:
        got = solution(order)
        flag = "OK " if got == expected else "FAIL"
        print(f"[{flag}] {order} -> {got} (expected {expected})")
