"""
프로그래머스 Lv2 - 원형 수열의 원소
2026-08-04 (Week 16)

────────────────────────────────────────────────────────────
[문제]
자연수로 이루어진 '원형 수열'(처음과 끝이 연결된 수열)에서,
연속하는 부분 수열의 합으로 만들 수 있는 서로 다른 수가 몇 가지인가?

예) elements = [7, 9, 1, 1, 4]
  원형이므로 [4, 7] 같이 끝→처음으로 넘어가는 부분 수열도 가능하다.
  답: 18

[제한사항]
  3 ≤ len(elements) ≤ 1,000
  1 ≤ elements[i]  ≤ 1,000
────────────────────────────────────────────────────────────
"""

from itertools import accumulate


# ============================================================
# v1 — 최초 통과 버전 (O(N^3))
# ============================================================
def solution_v1(elements):
    n = len(elements)
    extended_elements = elements + elements[:-1]      # 원형을 선형으로 확장
    result_set = set()

    for length in range(1, n + 1):
        for i in range(n):
            current_sum = sum(extended_elements[i:i + length])   # ← 여기가 O(length)
            result_set.add(current_sum)

    return len(result_set)


# ============================================================
# v2 — 누적합 버전 (O(N^2))  ★ 채택
# ============================================================
def solution(elements):
    n = len(elements)
    # 1. 원형 처리를 위해 배열 확장 (2n-1 이면 충분 — 아래 설명 참조)
    extended = elements + elements[:-1]

    # 2. 누적합. ★ 앞에 0을 붙이는 것이 핵심
    #    [0, e0, e0+e1, ...] → 구간 [i, i+L) 합 = P[i+L] - P[i]
    prefix_sums = [0] + list(accumulate(extended))

    result_set = set()

    # 3. 길이 × 시작점을 돌며 구간합을 O(1)로 계산
    for length in range(1, n + 1):
        for i in range(n):
            current_sum = prefix_sums[i + length] - prefix_sums[i]
            result_set.add(current_sum)

    return len(result_set)


# ============================================================
# 복잡도
# ============================================================
# v1: O(N^3)  — length N번 × i N번 × sum() 자체가 length번
#     ⚠️ `sum(ext[i:i+L])` 은 한 줄이지만 상수가 아니다.
#        슬라이싱이 새 리스트를 만들고(O(L)) 그걸 다시 더한다(O(L)).
#        이게 복잡도 사전 체크(실수 패턴 7번)의 사각지대.
#
# v2: O(N^2)  — 전처리 O(N) + 이중 루프 N^2, 각 구간합은 O(1)
#     N=1000 → 10^6. 실측 0.277s (v1은 수십 초 급)
#
# ★ O(N^2)이 이 문제의 하한: 부분수열이 약 N^2개이고
#   각각의 합을 알아야 하므로 더 줄일 수 없다.
#
# ⚠️ v1이 채점을 통과한 것은 sum()이 C 구현이라 상수가 작고
#    테스트가 최대 크기를 안 썼기 때문.
#    **"통과했다" ≠ "복잡도가 맞다"**


# ============================================================
# 사고 과정 / 피드백
# ============================================================
#
# ── 1. v1 → v2 로 가는 핵심 질문 ───────────────────────────
#
#   "길이 L 부분합에서 길이 L+1 부분합으로 갈 때
#    처음부터 다시 더해야 하나?"
#     → 아니다. 끝에 원소 하나가 추가될 뿐이다.
#
#   ★ 지난주 롤케이크에서 등록한 그 패턴:
#     **매번 재계산하지 말고 변하는 것만 갱신.**
#     거기선 경계를 밀었고, 여기선 길이를 늘린다.
#
#   두 가지 구현이 가능하고 둘 다 O(N^2):
#     (가) 롤링   — prev[i] = i에서 시작하는 길이 L 합.
#                   길이 L+1은 prev[i] + ext[i+L]
#     (나) 누적합 — P[j] - P[i] 로 임의 구간을 O(1)
#   → (나) 채택. 상태(prev 배열)를 들고 굴릴 필요가 없고,
#     accumulate가 C 레벨 루프라 상수가 작다.
#
#
# ── 2. ⚠️ accumulate 에 대한 오해 정정 ─────────────────────
#
#   "accumulate 를 쓰는 게 가장 복잡도가 낮다" → 정확하지 않다.
#
#   accumulate 는 (나) 누적합의 구현 수단일 뿐이고,
#   롤링 방식과 **복잡도가 똑같이 O(N^2)** 이다.
#   차이는 상수 항(파이썬 for vs C 레벨 루프)뿐.
#
#   v1(O(N^3)) → v2(O(N^2)) 로 내려간 이유는
#   accumulate 가 특별해서가 아니라 **sum() 재계산을 없앴기 때문**.
#
#   ★ 구분할 것: "복잡도가 낮다" ≠ "빠르다"
#
#
# ── 3. ★★ [0] 을 앞에 붙이는 이유 (이 풀이의 핵심) ─────────
#
#   prefix_sums = [0] + list(accumulate(extended))
#
#   0을 안 붙이면 i=0 일 때 "빼는 값이 없는" 특수 케이스가 생겨
#   `if i == 0:` 분기가 필요해진다.
#   0은 '빈 prefix'를 명시적으로 표현하는 패딩이다.
#
#   ★ 실수 패턴 12번 / 13번 그대로:
#     **예외를 처리하는 게 아니라 예외가 생기지 않게 만든다.**
#     (어제 택배상자에서 "루프를 입력 기준으로 돌면
#      종료 조건이 필요 없다"와 같은 발상)
#
#
# ── 4. 왜 elements * 2 가 아니라 elements[:-1] 인가 ────────
#
#   인덱스 계산으로 답한다:
#     - 시작 i 는 0..n-1, 길이 L 은 1..n
#     - 최대 접근 인덱스 = i + L - 1 = (n-1) + (n-1) = 2n-2
#     - 따라서 배열 길이는 2n-1 이면 충분
#     - elements + elements[:-1] = n + (n-1) = 2n-1  ✅
#
#   즉 가장 긴 창(길이 n)이 가장 늦은 시작점(i=n-1)에서 출발해도
#   2n-2 에서 끝난다. 2n-1 번째 원소는 어떤 (i, L) 로도 도달 불가.
#
#   ⚠️ elements * 2 로 해도 **틀리지는 않는다.** 원소 하나가 놀 뿐.
#      정확성 문제가 아니라 "필요한 만큼만 만들었다"는 정밀함의 문제.
#
#   ⚠️ 인덱스 상한이 딱 맞는 건 우연이 아니다:
#      최대 i+length = (n-1) + n = 2n-1 = len(prefix_sums)-1.
#      [:-1] 과 [0]+ 가 서로 맞물린 결과라 하나만 바꾸면 깨진다.
#
#
# ── 5. 더 줄일 수 있는 상수 (선택) ─────────────────────────
#
#   for length in range(1, n + 1):
#       result_set.update(prefix_sums[i+length] - prefix_sums[i]
#                         for i in range(n))
#
#   set.update 로 배치 삽입 → 파이썬 레벨 add 호출 n번이 사라진다.
#   **복잡도는 동일**, 상수만 준다. 지금도 0.277s 라 불필요하지만
#   "set 연산도 배치로 묶을 수 있다"는 건 알아둘 것.
#
#
# ── 6. 등록할 패턴 ──────────────────────────────────────────
#
#   ★ 구간 합을 여러 번 물어보는 문제 = 누적합 전처리
#     P = [0] + accumulate(arr) → 구간 [i, j) 합 = P[j] - P[i], O(1)
#     ★★ [0] 을 앞에 붙이는 것이 핵심 (i=0 특수 분기 제거)
#
#   ★ 원형 수열 = 배열을 이어붙여 선형으로
#     길이는 arr + arr[:-1] = 2n-1 이면 충분
#     (최대 접근 인덱스가 (n-1)+(n-1) = 2n-2 이므로)


# ============================================================
# 테스트  (⚠️ 기대값은 손으로 세고 근거를 남긴다 — 실수 패턴 21번)
# ============================================================
if __name__ == "__main__":
    import random
    import time

    # (1) 문제 예시
    print(f"[예시] [7,9,1,1,4] -> {solution([7,9,1,1,4])} (expected 18)")

    # (2) v1 과 교차 검증 — 기대값을 감으로 적는 대신 v1을 정답지로 쓴다
    mismatch = 0
    for _ in range(300):
        n = random.randint(3, 9)
        e = [random.randint(1, 10) for _ in range(n)]
        if solution(e) != solution_v1(e):
            print(f"[FAIL] {e}: v2={solution(e)} v1={solution_v1(e)}")
            mismatch += 1
    print(f"[{'OK ' if mismatch == 0 else 'FAIL'}] 랜덤 300케이스 v1 대조")

    # (3) 최대 입력 성능
    e = [random.randint(1, 1000) for _ in range(1000)]
    t = time.perf_counter()
    r = solution(e)
    print(f"[성능] n=1000 -> {r} ({time.perf_counter() - t:.3f}s)")
