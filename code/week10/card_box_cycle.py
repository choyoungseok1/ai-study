#        대부분 복잡도가 아니라 무한루프 신호. 손으로 [2,1] 돌려보면 바로 보였음.
#
# [4] 출발점 한 칸 건너뜀
#     `now = cards[i]` 는 i+1번 상자를 '이미 연 결과'부터 시작한 것.
#     임의의 상자를 고르는 거니 출발은 상자 번호 그 자체 -> `now = i + 1`.
#
# [5] 이중 인덱싱 IndexError
#     `cards[cards[...]]` 꼴은 범위를 벗어나기 쉽다.
#     while을 "이동 후 검사"가 아니라 "현재 상자 검사 -> 기록 -> 이동" 순서로 바꾸니
#     이중 인덱싱이 사라지고 IndexError가 원천봉쇄됐다.
#     now는 항상 1~n 범위라 cards[now-1]은 절대 범위를 안 벗어난다.
#
# [6] 중복 사이클 (효율성)
#     i마다 처음부터 추적하면 같은 사이클이 여러 번 만들어진다.
#     visited set으로 "이미 방문한 상자에선 시작 안 함" 처리 -> 각 상자 정확히 1번, O(n).
#
# [7] 점수 계산 오해
#     `len(set(temp))` (서로 다른 그룹 개수)가 아니라
#     "가장 큰 두 사이클 길이의 곱"이다.
#     덤: 리스트는 unhashable이라 set()에 못 넣는다 (그래서 에러도 났음).
#     => 길이만 sizes에 모아서 정렬하면 깔끔.
#
# [8] 엣지 케이스 (마지막 런타임 에러)
#     전체가 한 바퀴면 사이클이 1개뿐 -> 2번 그룹이 없어 0점.
#     sizes[1] 접근 전에 `if len(sizes) < 2: return 0` 필수.
#
