"""
프로그래머스 Lv2 - 숫자 카드 상자 게임 (순열 사이클 분해)
풀이 날짜: 2026-06-23 (Week 10, 시험 끝나고 복귀 첫날)

[문제 요약]
- 1~n번 상자가 일렬로 있고, i+1번 상자 안에는 cards[i] 숫자가 들어있다.
- 임의의 상자에서 시작해, "상자 안 숫자 → 그 번호의 상자"를 이미 연 상자를
  만날 때까지 따라간다. 이렇게 연 상자 묶음이 한 '그룹'.
- 남은 상자에서 또 한 그룹을 만든다.
- 점수 = (1번 그룹 크기) x (2번 그룹 크기) 의 최댓값.

[핵심 아이디어]
- cards는 1~n의 중복 없는 자연수 = 완벽한 순열.
- "i+1번 상자 -> cards[i]번 상자"를 간선으로 보면, 순열은 여러 개의
  사이클(cycle)로 쪼개진다. 각 사이클이 곧 하나의 '그룹'.
- 따라서 모든 사이클의 '길이'를 구해서, 가장 긴 두 개를 곱하면 최고 점수.
- 임의 시작점을 어디로 잡든 같은 사이클은 같은 그룹이므로,
  visited로 한 번 밟은 상자는 다시 시작점으로 쓰지 않는다 -> 각 상자 1회, O(n).
"""


def solution(cards):
    sizes = []          # 각 사이클(그룹)의 길이를 모음
    visited = set()     # 이미 어떤 그룹에 들어간 상자 번호

    for i in range(len(cards)):
        if (i + 1) in visited:      # 이미 방문한 상자면 새 사이클 시작 안 함
            continue

        cycle = []
        now = i + 1                 # ★ now = "지금 서 있는 상자 번호" (의미 고정)
        while now not in cycle:     # 현재 상자가 처음 보는 거면
            cycle.append(now)       #   기록하고
            visited.add(now)        #   전역 방문 표시
            now = cards[now - 1]    #   한 칸 이동: now번 상자 안 숫자가 다음 상자 번호

        sizes.append(len(cycle))    # 길이만 저장하면 충분

    sizes.sort(reverse=True)        # 내림차순
    if len(sizes) < 2:              # 사이클이 1개뿐 = 2번 그룹 없음 = 0점
        return 0
    return sizes[0] * sizes[1]      # 가장 큰 두 그룹의 크기 곱


if __name__ == "__main__":
    print(solution([8, 6, 3, 7, 2, 5, 1, 4]))  # 6  (사이클 길이 3, 2, ... )
    print(solution([3, 1, 2]))                  # 0  (1->3->2->1, 한 바퀴라 그룹 1개)
    print(solution([2, 1]))                     # 0  (1->2->1, 그룹 1개)


