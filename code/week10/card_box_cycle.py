#     상자 하나 열면 한 칸이니 `cards[now-1]` 한 번이 맞다.
#
# [3] append / while 조건 불일치 -> 무한루프 (TLE의 진짜 정체)
#     temp2엔 now를 넣는데 조건은 cards[now-1]을 검사하는 식으로 섞여 있었다.
#     넣는 값과 검사 값이 다르면 종료 조건이 영원히 안 맞아 while이 안 끝난다.
