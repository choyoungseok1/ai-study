"""
프로그래머스 Lv2 — 두 큐 합 같게 만들기
2026-08-11 (Week 17)

핵심 유형: 원형 버퍼 위의 가변 크기 투 포인터 + 증분 합
"""

# ═══════════════════════════════════════════════════════════
# [1] 문제 설명
# ═══════════════════════════════════════════════════════════
"""
길이가 같은 두 큐가 주어진다. 한 큐에서 pop하여 다른 큐에 insert하는 작업을
반복해 두 큐의 원소 합을 같게 만들 때 필요한 최소 작업 횟수를 구한다.
불가능하면 -1.

제한사항
- 1 ≤ len(queue1) = len(queue2) ≤ 300,000
- 1 ≤ 원소 ≤ 10^9   ★ 원소가 모두 양수라는 점이 핵심 (아래 참조)

─────────────────────────────────────────────────────────────
★★ 관찰 1 — 자료구조를 실제로 옮길 필요가 없다

원소의 상대 순서는 절대 바뀌지 않는다. queue1도 queue2도 앞에서부터
소비되고, 옮겨진 원소는 뒤에 쌓일 뿐이다.

따라서 A = queue1 + queue2 를 만들고 창 [l, r) 을 queue1 이라고 보면,
  - 합 > T  →  l += 1   (queue1에서 pop)
  - 합 < T  →  r += 1   (queue2에서 pop해 queue1에 붙임)
  - 작업 횟수 = l + (r - n)
원소를 옮기는 게 아니라 창을 미는 것이다.

★★ 관찰 2 — 그 창은 직선이 아니라 '원형'이다

r 이 2n 에 닿으면 queue2 의 '원래' 원소는 소진된다. 그런데 queue2 가
빈 게 아니다 — queue1에서 pop된 A[0:l] 이 거기 쌓여 있다.
그래서 다음에 당길 것은 A[0] 이고, 인덱스는 A[r % 2n] 이 된다.

⚠️ 이걸 놓치면 정답이 있는데 -1 을 반환하거나 IndexError 가 난다.
   실제로 아래 케이스가 반례다:
     queue1=[2,7,6,6,2], queue2=[3,3,2,6,1]  → 정답 10
   직선 창(r ≤ 2n)으로 풀면 "해 없음"이 나온다.

★ 관찰 3 — 왜 투 포인터가 성립하나
   모든 원소가 양수이므로 창을 넓히면 합이 반드시 늘고 좁히면 반드시 준다.
   단조성이 있어야 "크면 왼쪽, 작으면 오른쪽"이 옳다. 음수가 섞이면 무너진다.

─────────────────────────────────────────────────────────────
★ -1 판정

총합이 홀수면 즉시 불가능. 그 외의 불가능은 별도 조건 없이
'상한까지 돌았는데 못 찾음'으로 자연히 걸러진다.

⚠️ "어떤 원소가 절반보다 크면 불가능"은 결론이 맞지만 불필요한 조건이다.
   조건을 늘리면 검증할 것과 실수할 자리가 함께 는다.
"""


# ═══════════════════════════════════════════════════════════
# [2] 반복 상한 — 여기가 이 문제의 진짜 난점
# ═══════════════════════════════════════════════════════════
"""
루프를 언제 끊고 -1 을 낼 것인가. 감으로 정하면 안 된다.

⚠️ 오답 1 — "len(q1) + len(q2) - 1 = 2n-1"
   근거: "q1을 전부 비우고 q2를 거의 전부 당기면 최악"
   → 한 시나리오를 세고 일반화한 것. 반례가 있다:
     queue1=[1,1,4,1,6], queue2=[1,6,5,6,3]  → 정답 10 > 2n-1 = 9

   추적하면 l = 6 > n = 5 다. q1을 다 비운 뒤에도 계속 pop했다.
   q2로 넘어간 원소가 q1 앞에 서서 또 pop되기 때문이다.

★ 올바른 유도 — 원형이라는 점에서 나온다
   창의 시작점 l 은 원형이므로 2n 주기로 상태가 반복된다.
   같은 상태를 두 번 볼 이유가 없으니 l < 2n.
   각 l 에 대해 창은 최대 한 바퀴이므로 r ≤ l + 2n.
   따라서 작업 수 = l + r - n < 2n + 4n - n = 5n.

   → **증명 가능한 상한은 5n.**
   실측 최악은 ops/n ≈ 2.17 이라 3n 으로도 통과하지만,
   방어할 수 있는 수는 5n 이다. (지침 5번: 탐색 범위는 수학적 근거로)
"""


# ═══════════════════════════════════════════════════════════
# [3] 복잡도
# ═══════════════════════════════════════════════════════════
"""
포인터 전진 최대 5n, 전진 1회당 O(1)  →  n=300,000 이면 1,500,000회.
파이썬 임계(10^7~10^8) 아래이므로 통과.

⚠️ 단 합은 반드시 증분 갱신이어야 한다.
   매 반복 sum()을 다시 부르면 5n × n = 4.5×10^11 로 터진다.

★ 어제(할인 행사)는 재계산으로 충분했는데 오늘은 안 되는 이유:
   창 크기가 고정 10이 아니라 최대 2n 까지 커진다.
   "재계산이냐 증분이냐"는 취향이 아니라 창 크기가 상수인지에 달렸다.
"""


# ═══════════════════════════════════════════════════════════
# [4] 제출 코드 (통과)
# ═══════════════════════════════════════════════════════════
def solution_submitted(queue1, queue2):
    n = len(queue1)
    total = sum(queue1) + sum(queue2)
    if total % 2:
        return -1
    T = total // 2
    A = queue1 + queue2
    l, r = 0, n
    s = sum(queue1)
    for _ in range(3 * n):                 # ⚠️ 근거는 실측, 증명은 5n
        if s == T:
            return l + r - n
        if s > T:
            s -= A[l]                      # ⚠️ 여기만 % 가 없다 (비대칭)
            l += 1
        else:
            s += A[r % len(A)]             # ★ 원형 처리 — 정확하다
            r += 1
    return -1


"""
★ r % len(A) 를 붙인 것이 이 풀이의 핵심이고, 정확하다.
  IndexError 회피처럼 보이지만 의미상으로도 옳다 — queue2 에는
  queue1 에서 넘어온 원소가 쌓여 있고, 다음 pop 대상이 정확히 A[0] 이다.

⚠️ 지적 두 가지 (버그는 아님)

(a) l 에는 % 가 없어 비대칭이다.
    상한이 3n 인 구조에서 l 이 2n 을 넘을 수 있고 그러면 IndexError 다.
    실측상 발생하지 않지만 "왜 안전한지"가 코드에 없다.
    → 둘 다 % 를 붙이거나, 불변식을 주석으로 남긴다.

(b) 3 * n 의 근거가 코드에 없다.
    5n 으로 올리면 증명 가능해지고 비용은 거의 늘지 않는다
    (해가 있으면 그 전에 반환되므로 최악에만 영향).
"""


# ═══════════════════════════════════════════════════════════
# [5] 개선 코드
# ═══════════════════════════════════════════════════════════
def solution(queue1, queue2):
    n = len(queue1)
    total = sum(queue1) + sum(queue2)
    if total % 2:
        return -1

    T = total // 2
    A = queue1 + queue2
    m = 2 * n                       # 원형 버퍼 길이

    l, r = 0, n                     # 창 [l, r) = 현재 queue1 (원형)
    s = sum(queue1)                 # 창의 합 — 이후 sum() 재호출 없음

    # 상한 5n: l < 2n (상태가 2n 주기로 반복) + r ≤ l+2n (창은 최대 한 바퀴)
    for ops in range(5 * n):
        if s == T:
            return ops              # ★ l + r - n 과 같다. 전진 1회 = 작업 1회
        if s > T:
            s -= A[l % m]
            l += 1
        else:
            s += A[r % m]
            r += 1
    return -1


"""
바뀐 점
- 5 * n 으로 상한을 증명 가능한 값에 맞춤
- l 에도 % m 을 붙여 원형 처리를 대칭으로
- m = 2 * n 을 한 번만 선언 (어제 W=10 과 같은 발상: 같은 상수를 흩뿌리지 않는다)
- 반환값을 ops 로 — 루프 카운터가 곧 작업 수다.
  l + r - n 을 따로 계산하면 두 식이 어긋날 여지가 남는다.
  ⚠️ 이게 성립하는 이유: 매 반복 l 또는 r 이 정확히 하나씩 전진하고,
     l 의 전진과 r 의 전진이 각각 작업 1회이기 때문.
"""


# ═══════════════════════════════════════════════════════════
# [6] 피드백 — 대화 과정 전체 기준
# ═══════════════════════════════════════════════════════════
"""
★★ 1. 원형 구조를 스스로 잡아냈다 (오늘 최고 수확)

   힌트는 "이어붙인 배열의 창을 민다"는 직선 모델이었다.
   거기에 r % len(A) 를 붙여 원형으로 고친 것은 본인 판단이다.
   그리고 그게 정답이었다 — 직선 모델은 실제로 오답을 낸다.

   ★ 주어진 틀이 틀렸을 때 고칠 수 있는 것이 그 틀을 따르는 것보다 낫다.
     면접에서 이 문제가 나오면 "왜 % 인가"를 반드시 설명해라.

⚠️ 2. 상한을 한 시나리오로 일반화했다 (어제 22번과 같은 계열)

   "q1 전부 + q2 거의 전부 = 2n-1" 은 특정 경로를 센 것이지
   최악을 센 것이 아니다. 어제 창 개수를 나눗셈으로 센 것과 구조가 같다.

   ★ 규칙화: 상한은 "이 경우면 이만큼"이 아니라
     **"변수가 갈 수 있는 최대 범위"** 로 잡는다.
     여기서는 l 과 r 이 각각 어디까지 갈 수 있는가.

⚠️ 3. -1 조건을 과하게 잡았다

   "원소가 절반보다 크면 불가능"은 참이지만 불필요하다.
   상한 루프가 이미 걸러낸다. 조건을 늘리면 검증 대상이 늘고
   그 조건 자체가 틀릴 위험이 생긴다. **필요한 최소만 넣는다.**

✅ 4. 투 포인터를 스스로 지목했다

   "더 큰 쪽에서 popleft를 반복해서 세면 되나"는 정확히 투 포인터다.
   어제는 문제 이해 자체가 막혔는데 오늘은 알고리즘까지 스스로 갔다.

★★ 5. 코치의 정답지가 틀렸다 — 이번 세션의 가장 큰 교훈

   교차검증용 브루트포스를 l ≤ r ≤ 2n 으로 잘라 만들었고,
   그 결과 정답인 제출 코드를 "161건 불일치"로 오판했다.
   원형 경로를 정답지 쪽에서 빼먹은 것이다.

   ★ 지침 21번은 "느리지만 확실한 구현을 정답지로"인데,
     '확실한'의 근거를 대지 않으면 정답지도 틀린다.
     인덱스 트릭이 들어간 순간 그건 이미 최적화지 정답지가 아니다.
     → 정답지는 **정의 그대로**(deque 로 실제로 옮기는 시뮬레이션)여야 한다.

   → 지침 신규 등재 24번:
     "정답지도 검증 대상이다. 참조 구현에 최적화·수학적 축약이 섞이면
      그건 정답지가 아니라 두 번째 풀이다. 정의를 그대로 옮긴 구현만 정답지."
"""


# ═══════════════════════════════════════════════════════════
# [7] 교차검증  ★ 정답지는 '정의 그대로'
# ═══════════════════════════════════════════════════════════
from collections import deque


def solution_sim(q1, q2, cap=None):
    """정의 그대로. deque 로 실제로 옮긴다. 이것이 정답지.

    ⚠️ 인덱스 산술이나 상한 유도가 전혀 들어가지 않았다는 점이 중요하다.
       검증 대상과 같은 아이디어를 쓰면 같은 실수를 공유한다.
    """
    total = sum(q1) + sum(q2)
    if total % 2:
        return -1
    T = total // 2
    cap = cap if cap is not None else 100 * len(q1)

    a, b = deque(q1), deque(q2)
    sa = sum(q1)
    for step in range(cap):
        if sa == T:
            return step
        if sa > T:
            if not a:
                return -1
            x = a.popleft(); sa -= x; b.append(x)
        else:
            if not b:
                return -1
            x = b.popleft(); sa += x; a.append(x)
    return -1


if __name__ == "__main__":
    import random

    # ── 문제 예시 ────────────────────────────────────────
    assert solution([3, 2, 7, 2], [4, 6, 5, 1]) == 2
    assert solution([1, 2, 1, 2], [1, 10, 1, 2]) == 7
    assert solution([1, 1], [1, 5]) == -1
    print("예시 통과")

    # ── 상한 반례 (2n-1 로는 못 푸는 케이스) ─────────────
    assert solution([1, 1, 4, 1, 6], [1, 6, 5, 6, 3]) == 10      # 2n-1 = 9
    assert solution([2, 7, 6, 6, 2], [3, 3, 2, 6, 1]) == 10      # l > n 필요
    print("상한 반례 통과")

    # ── 랜덤 교차검증 ────────────────────────────────────
    random.seed(42)
    for trial in range(20000):
        n = random.randint(1, 7)
        a = [random.randint(1, 9) for _ in range(n)]
        b = [random.randint(1, 9) for _ in range(n)]
        got, exp = solution(a, b), solution_sim(a, b)
        assert got == exp, f"불일치 trial={trial} {a} {b} → {got} != {exp}"
    print("랜덤 교차검증 20,000건 통과")

    # ── 제출본도 함께 검증 ──────────────────────────────
    random.seed(43)
    for trial in range(20000):
        n = random.randint(1, 7)
        a = [random.randint(1, 9) for _ in range(n)]
        b = [random.randint(1, 9) for _ in range(n)]
        assert solution_submitted(a, b) == solution_sim(a, b), f"제출본 불일치 {a} {b}"
    print("제출본 교차검증 20,000건 통과")

    # ── 경계 ────────────────────────────────────────────
    assert solution([1], [1]) == 0                 # 이미 같음
    assert solution([1], [3]) == -1                # 홀수 아님(합 4)이지만 해 없음
    assert solution([2], [2]) == 0
    print("경계 통과")

    # ── 성능 (n=300,000) ────────────────────────────────
    import time
    n = 300_000
    big1 = [1] * n
    big2 = [1] * n
    t = time.time()
    r = solution(big1, big2)
    print(f"n={n:,} → {r} ({time.time()-t:.2f}초)")
