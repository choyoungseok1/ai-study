"""
프로그래머스 Lv2 - 마법의 엘리베이터
Day 90 (2026-07-11 소급) — 자리별 그리디 + carry

================================================================
풀이 과정 피드백 (시도 → 힌트 → 실수 → 수정)
================================================================

[아이디어] 각 자리수마다 min(내려가기 n, 올라가기 10-n).
  단, '올라가기'는 +1을 눌러 그 자리를 올림 → 윗자리에 carry(+1)가 넘어감.
  (예: 16 → 올림하면 십의 자리 1이 아니라 2가 됨. 문제 예시 16=6이 이걸 증명.)

[버그 1] 루프 범위 (실수패턴 #10 탐색범위).
  range(len(ls)-1) 로 돌려 '맨 윗자리(마지막 원소)'를 통째로 누락.
  → storey=5 가 0으로 나옴(루프가 한 번도 안 돎). 모든 답이 작게 나온 원인.

[버그 2] 마지막 원소 '예외처리'가 새 버그를 낳음.
  (a) ls[-1] 을 raw로 더함 → 윗자리가 5 이상이면 틀림(올림 판단 누락).
  (b) else 로 올림만 처리 → 윗자리를 올리면 '새 최상위 자리 1'이 생기는데
      그 1을 없애는 1번을 누락 (60=4로 나옴, 정답 5).
  → 교훈: 예외를 특별취급할수록 누락이 계속 생긴다.
     [해결] 큰자리 쪽에 여유 칸 0을 패딩(ls.append(0)) → 진짜 윗자리도
     루프 안에서 up/down 판단을 받고, 새 자리는 여유 칸이 흡수.
     그러면 마지막 answer += ls[-1] 은 항상 0/1이라 안전. (예외 자체 소멸)

[버그 3] 경계 n==5.
  이 자리 비용은 내림(5)·올림(5) 같지만, 올림하면 carry가 윗자리를 바꿔
  총합이 갈림. 규칙: 윗자리 ls[n+1] >= 5 면 올림(같이 올려태움), 아니면 내림.
  (예: 65 → 5를 올려 70 만들면 총 9, 내리면 10.)
  → BFS 검증기로 1~1000 전수 비교해 규칙 확정. (검증기 버튼범위도 한번 틀렸음
     — 푸는 쪽·검증 쪽 both 에서 #7 범위 산정 주의.)
================================================================
"""


def solution(storey):
    ls = []
    for num in str(storey):
        ls.insert(0, int(num))      # 작은자리 → 큰자리 순: 278 -> [8,7,2]
    ls.append(0)                    # 큰자리 쪽 carry 여유 칸 (예외처리 제거용)

    answer = 0
    for n in range(len(ls) - 1):
        if ls[n] < 5:               # 내림
            answer += ls[n]
        elif ls[n] > 5:             # 올림 → 윗자리로 carry
            answer += 10 - ls[n]
            ls[n + 1] += 1
        else:                       # ==5: 윗자리 보고 결정
            if ls[n + 1] >= 5:      # 어차피 올라갈 윗자리면 같이 올림
                answer += 10 - ls[n]
                ls[n + 1] += 1
            else:
                answer += ls[n]

    answer += ls[-1]                # 여유 칸(항상 0 또는 1)
    return answer


if __name__ == "__main__":
    for t, expected in [(16, 6), (2554, 16), (65, 9), (95, 6), (999, 2), (5, 5)]:
        got = solution(t)
        print(f"{t}: {got}  {'OK' if got == expected else 'X expected ' + str(expected)}")