#   역연산: -n(항상), ÷2(2로 나눠떨어질 때만), ÷3(3으로 나눠떨어질 때만).
#   나눗셈이 조건부라 대부분 노드에서 가지가 1~2개로 줄어 탐색 트리가 훨씬 얇음.
#   x→y 와 visited 크기를 비교하면 "역방향이 왜 나은가"가 손에 잡힘.
#   (100만 제약에선 x→y도 통과하지만, y→x가 더 적은 노드로 같은 답)
# ============================================================


if __name__ == "__main__":
    # 간단 테스트
    print(solution(10, 40, 5))    # 2  (×2 → ×2)
    print(solution(10, 40, 30))   # 1  (+30)
    print(solution(2, 5, 4))      # -1 (도달 불가)
