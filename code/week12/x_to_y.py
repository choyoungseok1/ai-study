"""
프로그래머스 Lv2 - x를 y로 만들기
========================================
Day 84 | Week 12 | 유형: BFS (최단경로)

[문제]
자연수 x를 y로 변환하려고 합니다. 사용할 수 있는 연산:
  - x에 n을 더한다
  - x에 2를 곱한다
  - x에 3을 곱한다
x, y, n이 매개변수로 주어질 때 x를 y로 만들기 위한 최소 연산 횟수를 return.
만들 수 없다면 -1을 return.

[제한사항]
  - x, y: 최대 1,000,000 (100만)

[핵심 아이디어]
"최소 연산 횟수" = x(뿌리)에서 y(목표)까지의 최단 경로.
각 수에서 갈 수 있는 곳이 3개(+n, ×2, ×3)인 그래프 → 최단경로이므로 BFS.
BFS는 레벨(깊이) 순으로 퍼지므로 y를 "처음 만나는 순간"이 곧 최단 깊이다.
(가중치 없는 그래프의 최소 단계/최단 거리 문제 = BFS)

[시간복잡도]
방문 상태는 y 이하 자연수 → 최대 약 100만 개.
각 노드에서 후보 3개 확인 O(1), visited가 set이라 조회/삽입 O(1).
→ 전체 O(y) ≈ 10^6. 시간 안에 통과.
("짜기 전에 규모부터" — 운으로 통과가 아니라 미리 알고 짠 것)
"""

from collections import deque


def solution(x, y, n):
    # x와 y가 같으면 연산 불필요 → 0
    # (이 처리 없으면 x==y일 때도 +n·×2·×3으로 다시 y를 만들려고 헛돎)
    if x == y:
        return 0

    # 큐: (현재 값, 연산 횟수) 튜플을 넣는다
    # ★ 값만 넣으면 "어떤 수인지"를 잃어버려 다음 연산을 적용 못 함 → 반드시 (값, 깊이)
    queue = deque([(x, 0)])

    # 방문 집합: 같은 수에 여러 경로로 도달 → 중복으로 큐에 쌓이는 폭발을 막음
    # ★ 시작값 x도 미리 넣어 x로 되돌아오는 것 차단
    visited = set([x])

    while queue:
        # ★ popleft() = 앞에서 꺼냄 = 큐 = BFS.
        #   pop()이면 뒤에서 꺼냄 = 스택 = DFS가 되어 최단 보장이 깨진다!
        current_value, count = queue.popleft()

        # 현재 값에서 가능한 3가지 연산 후보
        candidates = [current_value + n, current_value * 2, current_value * 3]

        for nxt in candidates:
            # y 도달 → 지금까지 횟수 + 1 이 곧 최단 (BFS라 처음 도달이 최단)
            if nxt == y:
                return count + 1

            # nxt < y 이고 미방문일 때만 큐에 추가
            # ★ nxt == y 는 바로 위에서 이미 처리했으므로 여기선 < 로 충분 (<= 아님)
            # ★ +n·×2·×3 은 값을 키우기만 하므로 y를 넘으면 되돌아올 수 없어 버린다
            # ★ visited.add 는 append 와 동시에! (꺼낼 때가 아니라 넣을 때 표시해야 중복이 안 쌓임)
            if nxt < y and nxt not in visited:
                visited.add(nxt)
                queue.append((nxt, count + 1))

    # 큐가 빌 때까지 y를 못 만들면 도달 불가 → -1
    return -1


# ============================================================
# [피드백 — 대화 과정에서 나온 실수와 교정]
# ============================================================
#
# 1. pop vs popleft  (치명적, 교정함)
#    - 처음에 pop()을 골랐음 → pop()은 뒤에서 꺼냄 = 스택 = DFS.
#    - 이 문제는 "최소" 연산이라 최단경로 필요 → 반드시 BFS(popleft).
#    - DFS면 먼저 파고든 긴 경로를 답으로 착각할 수 있어 최단 보장이 깨짐.
#    - 원칙: 가중치 없는 그래프의 "최소 단계/최단 거리" = BFS.
#            DFS는 "도달 가능?/완전 탐색/연결요소 세기" 용도.
#            (cf. 무인도 flood fill 은 "크기 다 세기"라 DFS/BFS 아무거나 OK였음.
#             이 문제는 "최소"라 BFS여야만 함 — 이게 갈림길.)
#
# 2. visited 필요성  ("필요없나?" → 필요함, 교정함)
#    - 방문 체크 없으면 같은 수에 여러 경로로 도달해 큐에 중복으로 쌓임.
#      예: x=2, n=2 → 2+2=4, 2×2=4 (두 경로). 중복이 깊이마다 지수 폭발.
#    - BFS는 "처음 도달 = 최단"이라 재방문은 무조건 같거나 더 긴 경로 → 볼 이유 없음.
#    - flood fill 에서 무한재귀 막던 visited 와 같은 이유 + 중복 제거.
#    - 넣는 타이밍: append 와 동시에 add (꺼낼 때가 아님).
#
# 3. 부등호 < vs <=  (실수 패턴 9 — 우연이 아니라 근거로 맞음)
#    - `nxt < y`로 충분한 이유: `nxt == y`를 바로 위에서 return으로 처리했으므로
#      이 if까지 내려오면 nxt는 y일 수 없음 → < 로 충분 (<= 써도 결과 동일).
#    - 만약 == 처리를 안 했다면 <= 여야 했음.
#      "왜 이 부등호인지" 근거를 댈 수 있으면 실수 안 남.
#
# 4. 시간복잡도 사전 체크  (실수 패턴 7)
#    - 짜기 전에 규모부터: 상태 ≤ 100만, 노드당 O(1) → O(y) 통과 예상.
#
# ------------------------------------------------------------
# [다음 학습 — 선택]
