"""
프로그래머스 Lv2 - 택배 배달과 수거하기
========================================
Day 88 | Week 12 | 유형: 그리디 (역순 누적 + 음수 여유)

[문제]
일렬로 나열된 n개의 집. i번째 집은 물류창고에서 거리 i.
트럭 용량 cap. 배달(창고→집)과 수거(집→창고)를 모두 마치고
창고로 돌아오는 최소 이동 거리를 구하라.
각 집마다 배달할 개수(deliveries)와 수거할 개수(pickups)가 주어짐.

[제한사항]
  - 1 ≤ cap ≤ 50
  - 1 ≤ n ≤ 100,000
  - 0 ≤ 원소 ≤ 50

[핵심 통찰 3개 — 이게 풀이의 전부]

① 왕복 비용 = "그 왕복에서 방문한 가장 먼 집"으로만 결정.
   중간 집들은 오가는 길에 공짜로 처리됨.
   → 어차피 가야 할 "가장 먼 미처리 집"까지 가면서 처리량을
     최대로 욱여넣는 게 낭비가 없다 = 그리디 정당화.
   → 순회는 뒤(n번 집)에서부터 역순으로.

② 배달과 수거는 트럭에 "동시에 실리는 순간이 없다".
   갈 때는 배달 상자만, 올 때는 빈 수거 상자만.
   → 한 왕복이 배달 cap개 + 수거 cap개를 "각각 독립적으로" 소화.
   → cap을 나눠 쓰는 게 아니라 각자 cap씩! (이게 이 문제의 관문)

③ 누적 수요를 음수까지 허용 = "여유 장부".
   왕복 하나가 뜨면 give -= cap, get -= cap (음수 가능).
   음수 = 그 왕복에 남은 여유 → 앞쪽(더 가까운) 집들의 수요를
   공짜로 흡수. 앞으로 이동하며 수요가 더해져 다시 양수가 되는
   순간 = 새 왕복이 필요한 순간.

[시간복잡도]
for O(n) + while 총 실행 = 전체 왕복 수 ≈ (수요합 / cap).
n=10만, 원소≤50, cap≥1 이어도 여유. "왕복마다 전체 재순회"
같은 O(n²) 시뮬레이션을 피한 것이 규모 통과의 핵심 (패턴 7).
"""


def solution(cap, n, deliveries, pickups):
    answer = 0

    # 배달/수거의 누적 필요량 (음수 = 이미 뜬 왕복의 남은 여유)
    give = 0
    get = 0

    # 뒤에서부터 (n-1 → 0) 역순 확인 — 가장 먼 미처리 집 기준
    for i in range(n - 1, -1, -1):
        give += deliveries[i]
        get += pickups[i]

        # 하나라도 양수 = 이 집까지 오는 왕복이 (추가로) 필요
        while give > 0 or get > 0:
            # 왕복 하나가 배달 cap + 수거 cap을 독립적으로 소화 (통찰 ②)
            # p만 양수여도 give -= cap 같이 까는 게 맞음 — 가는 길
            # 트럭은 어차피 비어있으니 배달 여유는 공짜로 생김
            give -= cap
            get -= cap

            # 현재 집(거리 i+1) 왕복 거리
            answer += (i + 1) * 2

    return answer


# ============================================================
# [피드백 — 대화 과정에서 나온 사고 흐름]
# ============================================================
#
# 1. 접근 전 규모 체크 (패턴 7)
#    - n=10만 → "왕복 하나씩 시뮬레이션하며 매번 전체 훑기"는 O(n²)
#      계열이라 불가. O(n) 한 번 훑기 구조를 먼저 목표로 잡음.
#
# 2. 그리디 도출 과정 (Q1→Q3 순서대로 스스로 답함)
#    - Q1 "이번 왕복은 어디까지?" → 처리 안 된 가장 먼 집.
#      (어차피 가야 하므로 거기까지 가는 게 손해 없음)
#    - Q2 "배달·수거가 트럭에 동시에 실리나?" → 없다.
#      ★ 이게 관문. 덕분에 한 왕복 = 배달 cap + 수거 cap 독립 소화.
#      while 안에서 give/get을 무조건 둘 다 까는 근거.
#    - Q3 "순회 방향?" → 가장 먼 곳 기준 = 뒤에서부터.
#
# 3. 음수 누적 트릭 ("여유 장부")
#    - 왕복이 뜰 때 cap을 까서 음수가 되면 = 여유.
#    - 앞쪽 집 수요가 그 여유에 흡수됨 (지나가는 길이라 공짜).
#    - 다시 양수 = 새 왕복 필요. 시뮬레이션 없이 왕복 수가 자동 계산됨.
#
# 4. 예시 검증 (cap=4, 답 16)
#    - i=4: give=2 → 왕복+10, give=-2, get=-4
#    - i=3: give=-1, get=0 → 왕복 X (여유가 4번 집 수거 4개 흡수)
#    - i=2: give=2 → 왕복+6
#    - i=1, i=0: 음수 유지 → 왕복 X
#    - 합 16 ✓ (예시의 왕복 구성과 정확히 일치)
#
# 5. 경계 처리
#    - range(n-1, -1, -1) 역순 정확 (패턴 9 안 걸림)
#    - while 조건 "give > 0 or get > 0" — 둘 중 하나만 남아도 왕복
"""
정리: 그리디 정당화(왕복비용=최원거리) + cap 독립(동시적재 없음)
+ 음수 여유 장부. 세 통찰을 스스로 도출해 한 번에 통과.
"""


if __name__ == "__main__":
    # 프로그래머스 예시
    print(solution(4, 5, [1, 0, 3, 1, 2], [0, 3, 0, 4, 0]))   # 16
    # 추가 케이스
    print(solution(2, 2, [0, 0], [0, 0]))                      # 0 (할 일 없음)
    print(solution(1, 1, [1], [1]))                            # 2 (1번 집 왕복 1회)
