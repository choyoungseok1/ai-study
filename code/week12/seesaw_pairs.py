#    - "토크 = 무게 × 거리"는 겉포장. 핵심은 "양쪽 (무게×거리)가 같으면 짝".
#    - 거리 2,3,4 조합 → 무게 비율 4종(1:1, 2:1, 3:2, 4:3)으로 환원.
#      이 환원이 풀이의 90%. 물리는 다 걷어낼 수 있었음.
#
# 2. ★ "같은 무게 두 사람은 같은 쌍? 다른 쌍?" — 스스로 던진 핵심 질문
#    - 답: 사람은 구별되므로 다른 쌍. → 그래서 곱셈으로 카운트.
#    - 이 질문이 곱셈(다른무게) vs 조합 k(k-1)/2(같은무게) 구분을 잡아줌.
#    - 같은 무게 k명끼리는 k² 아니고 k(k-1)/2 (자기자신·순서중복 제외).
#
# 3. 시간복잡도 사전 판단 (패턴 7)
#    - 처음엔 "그냥 이중 for문" 생각 → C(10만,2)=50억 → O(n²) 시간초과.
#    - "무게 종류 순회 + 인원 곱셈"으로 O(n) 전환이 이 문제의 정답 경로.
#    - 짜기 전에 규모부터 봤으면 이중 for문 후보를 바로 버렸을 것.
#
