#    - 제출본은 w*3/2, w*4/3 로 float 키 조회를 했는데 통과함.
#    - 통과 이유: (a) 파이썬이 150.0 == 150 을 True로 침(딕셔너리 조회 걸림),
#                (b) 무게 범위가 좁아(100~1000) float 오차가 안 생김.
#    - 즉 "이 문제라서 우연히" 통과. 범위가 크거나 나눗셈이 복잡했으면
#      299.9999998 같은 값이 in cnt 실패로 짝을 놓쳐 틀렸을 것.
