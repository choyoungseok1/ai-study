"""
프로그래머스 Lv2 - 시소 짝꿍
========================================
Day 87 | Week 12 | 유형: 해시(Counter) + 카운팅 / 시간복잡도

[문제]
시소 중심에서 2m, 3m, 4m 거리에 좌석이 있다. 두 사람이 마주 앉아
(무게 × 거리)가 양쪽 같으면 균형 = "시소 짝꿍".
weights가 주어질 때 시소 짝꿍이 몇 쌍인지 return.

[제한사항]
  - 2 ≤ len(weights) ≤ 100,000
  - 100 ≤ weights[i] ≤ 1,000 (정수, 단위 N)

[핵심 통찰 — 물리 걷어내기]
균형 조건: a × dA == b × dB   (a,b=무게 / dA,dB=거리 ∈ {2,3,4})
→ a : b = dB : dA. 거리 조합으로 나오는 무게 비율은 딱 4종:
   1:1, 2:1, 3:2, 4:3
즉 어떤 무게 w의 짝 상대는 정해져 있다(w, 2w, 3w/2, 4w/3 등).

[왜 "모든 쌍 비교"가 안 되나 — 시간복잡도(패턴 7)]
모든 쌍 비교 = C(100000, 2) ≈ 50억 → O(n²), 시간 초과.
대신 "무게 종류"만 순회(무게 100~1000이라 종류 ≤ 901개) + 인원수 곱셈
→ O(n). 이게 이 문제가 노리는 포인트.

[사람은 구별된다 → 곱셈으로 카운트]
무게 같아도 다른 사람 = 다른 쌍. 그래서:
  - 다른 무게 짝: cnt[a] * cnt[b]           (A그룹 각자 × B그룹 각자)
  - 같은 무게 짝(1:1): cnt[w] * (cnt[w]-1)//2  (k명 중 2명 뽑기, k²아님!)
중복 방지: 항상 "큰 무게 쪽"만 상대로 확인(한 방향으로만 세기).
"""

from collections import Counter


# ── 제출한 버전 (통과함) ─────────────────────────────
# 주의: w*3/2, w*4/3 이 float를 만든다. 이 문제 무게 범위(100~1000)가
#       좁아서 부동소수점 오차가 안 터졌고, 파이썬이 150.0 == 150 을
#       True로 쳐서 "우연히" 통과. 옳은 코드라서 통과한 게 아님.
def solution_submitted(weights):
    answer = 0
    cnt = Counter(weights)
    for w in cnt:
        if cnt[w] > 1:
            answer += cnt[w] * (cnt[w] - 1) // 2
        if w * 3 / 2 in cnt:          # ⚠ float 생성
            answer += cnt[w] * cnt[w * 3 / 2]
        if w * 2 in cnt:
            answer += cnt[w] * cnt[w * 2]
        if w * 4 / 3 in cnt:          # ⚠ float 생성
            answer += cnt[w] * cnt[w * 4 / 3]
    return answer


# ── 개선 버전 (구조적으로 옳음, 권장) ─────────────────
# 나눗셈 '/'을 아예 안 씀. w % 2 / w % 3 으로 "정수 되는 경우"만 거르고
# 정수나눗셈 '//'를 먼저 한 뒤 곱셈 → float를 원천 차단.
def solution(weights):
    answer = 0
    cnt = Counter(weights)
    for w in cnt:
        # 1:1 (같은 무게) — k명 중 2명 뽑기
        if cnt[w] > 1:
            answer += cnt[w] * (cnt[w] - 1) // 2
        # 3:2 — w가 '2'자리(작은 쪽)일 때 상대는 w//2*3. w 짝수일 때만 정수
        if w % 2 == 0 and w // 2 * 3 in cnt:
            answer += cnt[w] * cnt[w // 2 * 3]
        # 2:1 — 상대 2w, 항상 정수
        if w * 2 in cnt:
            answer += cnt[w] * cnt[w * 2]
        # 4:3 — 상대 w//3*4. w가 3의 배수일 때만 정수
        if w % 3 == 0 and w // 3 * 4 in cnt:
            answer += cnt[w] * cnt[w // 3 * 4]
    return answer


